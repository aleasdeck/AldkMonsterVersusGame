  roster: string[];
  /** Акт забега (0..2) для масштабирования врагов; null — без масштабирования. */
  act: number | null;
  /** С какого хода враги впадают в ярость (v0.46, ENRAGE_TURN по самому сильному рангу боя); нет — как у рядового боя. */
  enrageAt?: number;
  /** Испытание локации, под которым идёт бой (v0.48); нет — без испытания. */
  trial?: string | null;
  /** Благословение локации, под которым идёт бой (лёгкая сложность, data/boons.ts); нет — без благословения. */
  boon?: string | null;
