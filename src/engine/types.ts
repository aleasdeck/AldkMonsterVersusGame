// ─── Статусы ───────────────────────────────────────────────────────────────

export type StatusId =
  | 'strength' // +value к урону атак, до конца боя
  | 'weak' // урон атак −25 %, turns ходов
  | 'bleed' // v0.54: порции — каждое наложение тикает свои turns ходов, value — сумма живых порций (`parts`)
  | 'burn' // v0.54: срока нет (turns −1) — тик value, потом value делится пополам (`hold` — одно деление пропускается)
  | 'stun' // пропуск следующего действия (только враги)
  | 'exhaust' // −value STA на следующем ходу (только герой)
  | 'dodge' // следующие value атак не наносят урона
  | 'thorns' // атакующий получает value урона
  | 'regen' // +value HP в начале хода
  | 'invuln' // не получает урона, turns ходов
  | 'poison' // v0.54: срока нет (turns −1) — тик value, потом value −1 («Токсиколог» убывание снимает)
  | 'stealth' // враги не видят героя; любая атака — удар в спину (крит мимо блока) и снимает статус (только герой)
  | 'vulnerable' // получает на 25 % больше урона от ударов и заклинаний (VULNERABLE_MULT), turns ходов
  | 'doom' // предсмертие: метка врага с onDeath — сам ничего не делает, но в подсказке видно, что случится после его гибели (только враги)
  | 'evade' // процентный уворот: удар или заклинание по владельцу с шансом value % мимо; раны (DoT) и шипы бьют всегда (только враги)
  | 'echo' // эхо удара: следующая атака героя в этом ходу повторяется (только герой, v0.38)
  | 'enchant' // стихийная заточка: каждый удар героя вешает на цель рану `element` силой value на 2 хода (только герой, v0.38.7)
  | 'charge' // заряд Мага (черта, v0.44): value зарядов, обычный удар тратит все (только герой)
  | 'rage' // ярость Берсерка (черта, v0.44): value накопленного урона до Неистовства (только герой)
  | 'fury' // неистовство (v0.44): +1 STA в начале хода и удары без усталости до конца хода (только герой)
  | 'cold' // холод (v0.47): копится; на COLD_FREEZE превращается в Оцепенение и обнуляется (только враги)
  | 'frozen' // оцепенение (v0.47): пропускает value своих ходов, считается оглушением для крита (только враги)
  | 'focus' // верный глаз (v0.47): следующий удар героя — крит наверняка, тратится им (только герой)
  | 'taunt' // насмешка (v0.47): в ход врагов Шипы и Ответный удар героя вдвое, враги бьют героя, а не союзника (только герой)
  | 'decay' // распад (v0.54): любое лечение носителя вдвое слабее, turns ходов; повтор обновляет срок
  | 'curse'; // проклятье (архетип «Проклятье», Doom Некробиндера): складывается и не убывает; враг с HP не выше value гибнет после своего хода (только враги)

export interface Status {
  id: StatusId;
  value: number;
  /** −1 — до конца боя. */
  turns: number;
  /** Стихия заточки (`enchant`): какая рана ложится с удара — Горение, Яд или Кровотечение. */
  element?: StatusId;
  /**
   * Порции Кровотечения (v0.54): каждое наложение — своя сила `v` и свой срок `t`, истекает само. `value` — их сумма,
   * `turns` — срок самой долгой. Так «Кровотечение 3 на 2 хода» стоит ровно 6, а не держится, пока герой бьёт.
   */
  parts?: { v: number; t: number }[];
  /** Горение, раздутое заклинанием («Раздуть», v0.54): в ближайший тик не гаснет вдвое. */
  hold?: boolean;
}

