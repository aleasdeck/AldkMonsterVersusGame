/**
 * Род типовой анимации приёма: взмах оружием в руке, стрела, магический снаряд, брошенная склянка.
 * Облако дебафа и свечение бафа выводятся из событий боя и в данных не задаются.
 */
export type FxKind = 'melee' | 'arrow' | 'orb' | 'flask';

/**
 * Эффект пиксельной лепки (v0.52.7, src/ui/fx/): своя анимация приёма вместо той, что выводится из рода снаряда.
 * На себя — `roar` (Боевой клич); снаряд по врагу — `fire` (огненный шар), `ice` (ледяной осколок), `bolt` (цепная
 * молния), `stone` (камень пращи). Стрела, склянка, взмах и сгусток лепятся по роду `kind` сами.
 */
export type SculptId = 'roar' | 'fire' | 'ice' | 'bolt' | 'stone';

/** Настройка типовой анимации: род (по умолчанию выводится из эффектов и оружия) и цвет; `sculpt` — эффект лепки. */
export interface FxSpec {
  kind?: FxKind;
  color?: string;
  sculpt?: SculptId;
  /**
   * Клип героя для приёма, если он не выводится из эффектов: Щитовой удар — удар щитом, Молот света — удар с сиянием
   * (иначе по лечению в эффектах он сыграл бы лечение на колено), Дымовая шашка — исчезновение в дыму. У героя-лепки
   * свой клип, у кого его нет — замена из таблицы (clips.ts, `instead`); рисованный подменяет по цепочке (heroSprite.ts,
   * `FALLBACK`).
   */
  clip?: 'bash' | 'smite' | 'vanish';
}

// ─── Артефакты ─────────────────────────────────────────────────────────────

export type TargetKind = 'enemy' | 'allEnemies' | 'self';

export type Effect =
  | {
      type: 'attack';
      bonus: number;
      target: 'enemy' | 'allEnemies';
      /** Доля урона оружия, 1 — полный. */
      mult?: number;
      sureCrit?: boolean;
      /** Доля нанесённого урона, которая становится Блоком героя (Щитовой удар): блок растёт вместе с оружием. */
      blockPct?: number;
      /** Столько стамины вернётся, если удар убьёт цель («Добивание»). */
      refundOnKill?: number;
      /** Прибавка к удару по раненой цели: HP не выше доли pct от максимума («Добивание», v0.38.3). */
      lowHp?: { pct: number; bonus: number };
      /** Око за око (v0.47): + доля урона, полученного героем за прошлый ход врагов. */
      revenge?: number;
      /** Кара (v0.47): + лечение героя за этот ход × smite. */
      smite?: number;
      /** Раскол (v0.47): по оцепеневшей цели удар ×vsFrozen и Оцепенение снимается. */
      vsFrozen?: number;
    }
  /**
   * Взорвать раны (v0.38): оставшийся урон перечисленных статусов на цели (сила × ходы) снимается и наносится сразу, ×mult,
   * как рана — мимо блока, без крита и уязвимости. `pooled` — по всем врагам: снятое со всех складывается и бьёт каждого («Взрыв пламени»).
   */
  | { type: 'detonate'; statuses: StatusId[]; target: 'enemy' | 'allEnemies'; mult: number; pooled?: boolean }
  /** Заражение: перечисленные статусы с цели копируются на всех остальных врагов (сила и срок те же, стакаются как обычно); pct — доля силы (Кровавая баня). */
  | { type: 'spread'; statuses: StatusId[]; target: 'enemy'; pct?: number }
  /** Испепеление (v0.43): урон = Горение цели × mult, как рана — мимо блока и уворота; Горение остаётся. */
  | { type: 'scorch'; mult: number; target: 'enemy' }
  /** Пролом щита: весь блок цели снимается и наносится ей уроном × mult — мимо блока, без кубика, усталости и крита. Без блока приём недоступен. */
  | { type: 'breakBlock'; mult: number; target: 'enemy' }
  /** Финишер: урон = (pct % среднего урона оружия с Силой) × число атак героя в этом ходу, без кубика и усталости; счётчик атак не растёт. Без атак недоступен. */
  | { type: 'finisher'; pct: number; target: 'enemy' }
  /**
   * Цепная атака: фиксированный удар без кубика, усталости и крита; атакой не считается. Доступна только по заряду —
   * каждый другой приём или заклинание в этом ходу даёт один (`chainCharges`), без заряда «Сначала примените приём».
   */
  | { type: 'chain'; amount: number; target: 'enemy' }
  /** Катализатор (v0.47): статус на цели ×mult; без статуса приём недоступен. */
  | { type: 'amplify'; status: StatusId; mult: number; target: 'enemy' }
  /** Обвал щита (v0.47): весь блок героя уходит, каждый враг получает pct потраченного — как удар, без кубика, усталости и крита. */
  | { type: 'blockBurst'; pct: number }
  /** Стихийная заточка: на turns ходов каждый удар героя вешает случайную рану (Горение, Яд или Кровотечение) силой value на 2 хода; стихия бросается при наложении. */
  | { type: 'enchant'; value: number; turns: number }
  /** Удар щитом (Таран): урон равен текущему Блоку героя × mult. Кубик оружия, Сила и усталость не участвуют, блок не тратится. */
  | { type: 'blockStrike'; mult: number; target: 'enemy' }
  /** vsWeak — множитель по цели со Слабостью (Ледяной осколок, v0.38): проверяется до статусов самого приёма. */
  | { type: 'spell'; amount: number; target: 'enemy' | 'allEnemies'; drain?: boolean; vsWeak?: number }
  | { type: 'block'; amount: number }
  | { type: 'heal'; amount: number }
  | { type: 'status'; target: TargetKind; status: StatusId; value: number; turns: number }
  | { type: 'gainSta'; amount: number }
  /**
   * Призыв существа из таблицы `ALLIES` (data/allies.ts) с числами тира призывающего артефакта. При полном ряде (MAX_ALLIES)
   * не пропадает, а подкармливает первое существо: половина HP призыва к HP и максимуму и Сила +1 (v0.56, правило Ости из StS2).
   */
  | { type: 'summon'; allyId: string; tier: ArtTier }
  /** Боевой рог (v0.56): все существа героя получают Силу amount до конца боя. Без существ недоступен. */
  | { type: 'allyBuff'; amount: number }
  /** Натравить (v0.56): все существа сразу бьют цель своим ударом (первым бьющим приёмом круга) +bonus; круг не сдвигается, свой ход они не теряют. */
  | { type: 'command'; target: 'enemy'; bonus: number }
  /** Трупный взрыв (v0.56): первое существо гибнет, каждый враг получает pct его HP — как рана, мимо блока. */
  | { type: 'sacrifice'; pct: number }
  /** Без спасения (архетип «Проклятье», No Escape из StS2): Проклятье цели растёт на amount и ещё на долю pct уже накопленного. */
  | { type: 'curseGrow'; amount: number; pct: number; target: 'enemy' }
  /** Знак обречённого: Проклятье + доля pct от HP, которое цель уже потеряла. По нетронутой цели недоступен. */
  | { type: 'curseLost'; pct: number; target: 'enemy' }
  /** Расплата: урон = Проклятье цели × mult, как рана — мимо блока; Проклятье снимается. Без Проклятья недоступна. */
  | { type: 'reckoning'; mult: number; target: 'enemy' }
  /** Конец дней (End of Days): каждый враг с HP не выше своего Проклятья гибнет сразу, не дожидаясь своего хода. */
  | { type: 'execute' }
  /** Герой ранит себя: мимо блока и защиты. Нельзя применить, если HP не больше amount. */
  | { type: 'selfDamage'; amount: number }
  | { type: 'gainMp'; amount: number }
  /** Снять с героя раны и проклятия: кровотечение, горение, яд, слабость, изнурение, уязвимость; statuses — только перечисленные (Глухая оборона). */
  | { type: 'cleanse'; statuses?: StatusId[] }
  /** Притянуть цель в первый ряд (Крюк-кошка): она встаёт под удар ближнего боя, остальные сдвигаются назад. */
  | { type: 'pull'; target: 'enemy' }
  /** Отбросить цель на клетку назад (Щитовой удар): следующий в ряду встаёт первым. Последнего в ряду толкать некуда. */
  | { type: 'push'; target: 'enemy' };

