/**
 * Правило ИИ «по приоритету» (v0.46): первое выполнимое правило задаёт намерение, иначе — цикл `order`.
 * Детерминированно, как цикл: игрок видит узор врага, а не бросок кубика.
 */
export interface PriorityRule {
  action: string;
  /** Условие реакции; вычисляется, когда враг выбирает следующее намерение (сразу после своего хода). */
  when?: (ctx: AiCtx) => boolean;
  /** Что за условие — для подсказки намерения и бестиария: «у героя Блок ≥ 6». */
  hint?: string;
  /** Не чаще, чем раз в N ходов. */
  cooldown?: number;
  /** Максимум раз за бой. */
  maxUses?: number;
}

/**
 * Роль врага (v0.46, план §5.3): задаёт место в ряду и правило позиции.
 * Впереди — страж, громила, рой; сзади — стрелок, заклинатель, поддержка.
 */
export type EnemyRole = 'guard' | 'brute' | 'swarm' | 'shooter' | 'caster' | 'support';

export interface BossRule {
  action: string;
  /** 0 — только через followUp. */
  weight: number;
  condition?: (ctx: AiCtx) => boolean;
  /** Не чаще, чем раз в N ходов. */
  cooldown?: number;
  /** Максимум раз за бой. */
  maxUses?: number;
  /** Обязательное следующее действие. */
  followUp?: string;
}

export interface EnemyDef {
  id: string;
  name: string;
  hp: number;
  location: LocationId;
  rank: 'normal' | 'elite' | 'boss';
  actions: EnemyAction[];
  ai: { type: 'cycle'; order: string[] } | { type: 'priority'; rules: PriorityRule[]; order: string[] } | { type: 'boss'; rules: BossRule[] };
  /** Роль в ряду (v0.46): у рядовых и элит; у боссов нет — они стоят, где стоят. */
  role?: EnemyRole;
  /** Процентный уворот при появлении (статус `evade`, 0..100): столько процентов ударов и заклинаний проходит мимо. */
  evade?: number;
  /** Регенерация с начала боя (v0.54, «стартовый прикол»): +N HP в начале каждого своего хода, растёт с актом, как лечение; Распад режет вдвое. */
  regen?: number;
  /** Срабатывает при смерти: деление, взрыв. */
  onDeath?: { name: string; effects: EnemyEffect[] };
  /**
   * Вторая фаза босса: как только HP опускается до доли `atHp` от максимума, босс тут же (ещё в ход героя) меняет
   * облик — разыгрывает `effects`, получает ауру цвета `aura` и `phase = 2`; правила ИИ различают фазы через `ctx.self.phase`.
   */
  /** Вторая фаза: порог доли HP, эффекты в момент перехода, аура и `guard` — что босс делает на ходу перехода вместо атаки (v0.36: блок, уклонение, неуязвимость или шипы на срок). */
  phase2?: { atHp: number; name: string; effects: EnemyEffect[]; guard: EnemyEffect[]; aura: string };
  /** Аура с появления: тело, вставшее после смерти босса (Развоплощённый лич, Призрак капитана). */
  aura?: string;
  sprite: SpriteSpec;
}

