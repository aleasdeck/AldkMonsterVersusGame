/**
 * Предел запястья при обратном хвате: клинок выходит из-под мизинца и в стойке продолжает предплечье (≈ +2° и +4°);
 * кисть отклоняется в обе стороны не больше, чем на 35°. Вне предела клинок встаёт поперёк предплечья, как при прямом
 * хвате, или ложится на него обухом.
 */
const WRIST: [number, number] = [-35, 35];
const nrm = (a: number): number => { a = ((a % 360) + 360) % 360; return a > 180 ? a - 360 : a; };
/** Угол клинка в координатах верха: покой — `sw`, клип — от предплечья (`a2 + wr`) с пределом запястья. */
function bladeAngle(sw: number, wr: number, ws: number, a2: number): number {
  const s = lerp(sw, a2 + wr, ws);
  if (ws <= 0) return s;
  const d = nrm(s - a2), c = Math.max(WRIST[0], Math.min(WRIST[1], d));
  return s + (c - d);
}

interface ArmSolve { sx: number; sy: number; ex: number; ey: number; hx: number; hy: number; a1: number; a2: number }

/**
 * Рука кистью в точке (tx, ty) от плеча (sx, sy): локоть — ik по ту же сторону от линии плечо — кисть, что в стойке
 * (обе руки листа чуть согнуты локтем наружу-вверх); кисть не дальше длины руки.
 */
function reachArm(sx: number, sy: number, tx: number, ty: number, l1: number, l2: number): ArmSolve {
  const vx = tx - sx, vy = ty - sy, d = Math.hypot(vx, vy), reach = l1 + l2 - 0.05;
  if (d > reach) {
    tx = sx + (vx * reach) / d;
    ty = sy + (vy * reach) / d;
  }
  const [ex, ey] = ik(sx, sy, tx, ty, l1, l2, -vy, vx);
  return { sx, sy, ex, ey, hx: tx, hy: ty, a1: Math.atan2(ey - sy, ex - sx) / DEG, a2: Math.atan2(ty - ey, tx - ex) / DEG };
}

/**
 * Плечевой сустав ходит за рукой, как у Паладина и Берсерка: поднятый локоть поднимает его до 3 единиц, кисть,
 * вынесенная к врагам дальше стойки, выносит вперёд до 2,5, поднятая кисть за плечом (замах) — уводит назад до 2.
 * Вынос считается от кисти в стойке (`rest`, с запасом 4): дальняя рука и в стойке висит впереди плеча, и прежняя
 * мерка от самого плеча сдвигала бы утверждённый покой.
 */
function followShoulder(sh: readonly number[], rest: number, solve: (sx: number, sy: number) => ArmSolve, l1: number): ArmSolve {
  const [sx0, sy0] = sh;
  const first = solve(sx0, sy0);
  const lift = Math.max(0, Math.min(1, (sy0 - first.ey) / l1 + 0.3));
  const fwd = Math.max(0, Math.min(1, (first.hx - Math.max(sx0 + 8, rest + 4)) / 26));
  const back = lift * Math.max(0, Math.min(1, (sx0 - first.hx) / 12));
  return lift > 0 || fwd > 0 ? solve(sx0 + 2.5 * fwd - 2 * back, sy0 - 3 * lift) : first;
}
const nearArm = (P: AssassinPose): ArmSolve =>
  followShoulder([M.armN.sh[0] + P.nsx, M.armN.sh[1] + P.nsy], M.armN.hand[0], (sx, sy) => reachArm(sx, sy, P.nhx, P.nhy, ARM_N.l1, ARM_N.l2), ARM_N.l1);
const farArm = (P: AssassinPose): ArmSolve =>
  followShoulder([M.armF.sh[0] + P.fsx, M.armF.sh[1] + P.fsy], M.armF.hand[0], (sx, sy) => reachArm(sx, sy, P.fhx, P.fhy, ARM_F.l1, ARM_F.l2), ARM_F.l1);

/**
 * Покой: лёгкое дыхание — верх с капюшоном поднимается на пиксель, таз оседает на четверть цикла позже, раз за цикл
 * вес переходит с ноги на ногу; стопы стоят, колени в малых сдвигах идут за тазом (урок Паладина). Руки не приклеены
 * к корпусу: кисти повторяют 40 % его движения, клинки качаются маятником ±1,5° вразнобой (при ±2,5° мерцал блик кромки); раз за цикл голова
 * подаётся к врагам — высматривает цель; полы колышутся. Сдвиги — целыми пикселями.
 */
function idlePose(p: Painter): AssassinPose {
  const P = { ...REST };
  P.crouch += p.bob(1.5, 2, 0.25);
  P.x += p.snap(1.2 * p.wave(1, 0.3));
  const bodyX = P.x, bodyY = P.crouch - p.bob(2, 2);
  P.nhx -= 0.6 * bodyX;
  P.nhy -= 0.6 * bodyY;
  P.fhx -= 0.6 * bodyX;
  P.fhy -= 0.6 * bodyY;
  // Рука почти прямая (сгиб 165° и 174°), и у предела длины ik неустойчив: сдвиг кисти на 60 % движения корпуса гонял
  // локоть на 4 пикселя. Длина плечо — кисть держится как в стойке, кисть качается вокруг плеча — сгиб постоянный.
  const keep = (sh: readonly number[], hand: readonly number[], x: number, y: number): [number, number] => {
    const l0 = Math.hypot(hand[0] - sh[0], hand[1] - sh[1]), a = Math.atan2(y - sh[1], x - sh[0]);
    return [sh[0] + l0 * Math.cos(a), sh[1] + l0 * Math.sin(a)];
  };
  [P.nhx, P.nhy] = keep(M.armN.sh, M.armN.hand, P.nhx, P.nhy);
  [P.fhx, P.fhy] = keep(M.armF.sh, M.armF.hand, P.fhx, P.fhy);
  P.nsw += 1.5 * p.wave(1, 0.45);
  P.fsw += 1.5 * p.wave(1, 0.7);
  P.turn = p.blink(0.62, 0.16);
  // Взгляд: голова подаётся к врагам и чуть клонится — один сдвиг без кивка читался «курицей».
  P.head += 2.5 * P.turn;
  P.cape = 0.5 - 0.5 * p.wave(1, 0.25);
  return P;
}

/** Поза кадра: ключи клипа поверх покоя в фазе 0 или сам покой. */
function framePose(p: Painter): AssassinPose {
  const base = idlePose(p);
  const c = clipAt(p);
  if (!c) return base;
  const clip = c.clip as AssassinClip;
  const keys = CLIPS[clip];
  const P = keys?.length ? poseAt(base, keys, c.f, c.n, HERO_CLIPS[c.clip].hold) : base;
  // Исчезновение: пока силуэт скрыт дымом, тело встаёт в покой — проступает из дыма уже в стойке.
  return P.home > 0.5 ? { ...base, smoke: P.smoke, thin: P.thin, fade: P.fade, home: 1 } : P;
}

