/**
 * Поза героя — поля как у Воина, Паладина и Берсерка (docs/lepka-geroev.md «Каркас позы»), обе руки ведутся кистью:
 * в каждой по клинку обратным хватом. Координаты кистей — в координатах верха (до наклона `lean`), углы клинков —
 * градусы по `at` (0 — к врагам, 90 — вниз), наклоны — градусы, плюс к врагам.
 */
export interface AssassinPose extends Record<string, number> {
  x: number; y: number;
  crouch: number;
  lean: number;
  head: number;
  /**
   * Ближняя рука (кинжал главный): кисть точкой; клинок — угол в координатах верха (`nsw`, покой) или от предплечья
   * (`nwr`) с долей `nws` (1 — от предплечья, в пределах запястья `WRIST`). Сдвиг плечевого сустава `nsx`/`nsy` —
   * разворот корпуса ближним плечом (к врагам — плюс), сверх того, что плечо ходит за рукой само.
   */
  nhx: number; nhy: number; nsw: number; nwr: number; nws: number; nsx: number; nsy: number;
  /** Дальняя рука — то же для второго клинка. */
  fhx: number; fhy: number; fsw: number; fwr: number; fws: number; fsx: number; fsy: number;
  /**
   * Слои рук: `nover` 1 — ближняя рука поверх накидки, головы и шарфа (кулак у лица, рука над плечом); `fback` 1 —
   * дальнее предплечье с клинком за туловищем (замах назад); `ffront` 1 — дальнее предплечье перед головой и шарфом
   * (клинки крестом перед лицом). По умолчанию ближняя рука под накидкой, дальнее предплечье перед туловищем.
   */
  nover: number; fback: number; ffront: number;
  footF: number; footN: number; liftF: number; liftN: number;
  /**
   * Ближнее колено на земле (смерть), `kneelF` — дальнее; таз опускать приседом (колено касается
   * земли при `crouch + y` ≈ 16). Сапог встаёт на носок.
   */
  kneel: number; kneelF: number;
  /** Полы и набедренная полоса: 0 — висят, 1 — отнесены назад (в клипах — до 3: выпад). */
  cape: number;
  /** Голова подаётся к врагам (взгляд), 0…1. */
  turn: number;
  /**
   * Смерть: `fall` 0 стоит → 1 лежит ничком на коленях (больше 1 — отскок от земли); `drop` — клинки выпали из рук и легли на
   * землю; `limp` — руки обмякли и висят по отвесу мира от плеча, у земли кулак ложится на неё.
   */
  fall: number; drop: number; limp: number;
  /** Искры о скрещённые клинки (блок). */
  spark: number;
  /**
   * Исчезновение (личный клип Дымовой шашки): `smoke` — дым встаёт от земли стеной (0 — нет, 1 — стена в рост), `thin` —
   * дым редеет и поднимается (1 — растаял); `fade` — силуэт растворяется по клеткам снизу вверх (1 — пропал) и
   * проступает обратно тоже снизу вверх; `home` 1 — тело уже в позе покоя (пока его не видно, оно встаёт в стойку).
   */
  smoke: number; thin: number; fade: number; home: number;
}

