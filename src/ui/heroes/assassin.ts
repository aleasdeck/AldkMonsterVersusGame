/** Варианты аватарки на обсуждении (шаг 5 рецепта). */
export type AssassinAvatar = 'a' | 'b' | 'c';

/**
 * Знак в ореоле прежнего портрета — череп в полумесяце: луна с вырезом сверху справа (`cut`), череп в вырезе — на тон
 * светлее луны, иначе глазницы на 44 клетках сливались с небом. Координаты — в радиусах ореола от его центра, y вниз (`AvatarSpec.emblem`). Глазницы и нос — дыры одного
 * многоугольника: обход черепа, потом каждая дыра обратным ходом с возвратом к началу (чётность пересечений оставляет
 * дыру пустой, а мостик туда и обратно сам себя гасит).
 */
const SKULL: number[] = (() => {
  const ring = (cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n: number): number[] => {
    const out: number[] = [];
    for (let k = 0; k <= n; k++) {
      const a = a0 + ((a1 - a0) * k) / n;
      out.push(cx + rx * Math.cos(a), cy + ry * Math.sin(a));
    }
    return out;
  };
  // Свод черепа — дуга сверху, скулы, челюсть с зубцами внизу.
  const outer = [
    ...ring(0.1, -0.12, 0.4, 0.36, Math.PI * 0.8, Math.PI * 2.2, 20),
    0.4, 0.16, 0.26, 0.22, 0.26, 0.36, 0.17, 0.4, 0.13, 0.34, 0.07, 0.4, 0.01, 0.34, -0.05, 0.4, -0.08, 0.36, -0.08, 0.22, -0.22, 0.16,
  ];
  const back = [outer[0], outer[1]];
  const hole = (pts: number[]): number[] => [...pts, pts[0], pts[1], ...back];
  const eye = (cx: number): number[] => ring(cx, -0.04, 0.11, 0.1, Math.PI * 2, 0, 10);
  const nose = [0.1, 0.1, 0.05, 0.2, 0.15, 0.2];
  return [...outer, ...back, ...hole(eye(-0.04)), ...hole(eye(0.24)), ...hole(nose)];
})();

/**
 * Цвета прежнего портрета: лиловое небо (светлее сверху, почти чёрное снизу), лиловая луна и череп, чёрные готические
 * шпили по краям. Рамка — темнее неба (урок Воина: яркая рамка выделяла лепку в ряду рисованных); на прежнем портрете
 * она светлее неба.
 */
const AVATAR_COLORS: AvatarSpec['colors'] = { top: '#421e4e', bottom: '#150818', halo: '#5a2a64', haloEdge: '#63306d', skyline: '#12071a', frameDark: '#0a0410', frame: '#2c1335', frameLight: '#4a2254' };
/** Готические шпили по краям: высокие и острые, как на прежнем портрете. */
const AVATAR_SKYLINE: AvatarSpec['skyline'] = [[0.04, 0.07, 0.6, 0.3], [0.12, 0.05, 0.46, 0.26], [0.19, 0.04, 0.36, 0.18], [0.87, 0.05, 0.44, 0.24], [0.95, 0.07, 0.62, 0.3]];

/**
 * Позы портрета — поза `AssassinPose`, как в клипах. Клинки в них — от кулака абсолютным углом (`nws`/`fws` 0), как в
 * стойке: в портрете клинок обратным хватом выходит из-под мизинца поперёк предплечья, а не продолжает его («факел»).
 * B — ближний кулак поднят перед грудью, клинок из-под мизинца вниз-вправо поперёк кадра (как на прежнем портрете);
 * C — оба кулака у пояса, клинки вверх накрест перед грудью, остриями к шарфу; дальняя рука — снаружи корпуса, за
 * ближней. Отвергнуто: клинки вниз накрест от кулаков у груди — дальнее предплечье ложилось поперёк груди бревном
 * (дальнее плечо под шарфом, кулак рядом с ним складывает руку), а клинки уходили за нижний край.
 */
const PORTRAIT_B: AssassinPose = { ...REST, head: 3, nhx: 66, nhy: 48, nsw: 55, nsx: 6 };
const PORTRAIT_C: AssassinPose = { ...REST, head: 4, nhx: 60, nhy: 66, nsw: -45, nsx: 3, fhx: 100, fhy: 64, fsw: -135 };

/**
 * Аватарка — бюст из той же лепки в кадре прежнего портрета: капюшон правее середины, луна с черепом над ним слева,
 * шпили по краям. A «Покой» — поза стойки (рецепт: «поза — сначала покой»): клинков в кадре нет, у правого нижнего
 * угла — дальний кулак; B «Клинок у груди» — ближний кинжал обратным хватом перед грудью, как на прежнем портрете;
 * C «Накрест» — оба кинжала остриями вверх накрест перед грудью. Кадр — левый верхний угол и сторона в единицах модели:
 * 88, как у соседей в ряду выбора (капюшон не крупнее шлема Воина); луна с черепом слева над капюшоном, как на прежнем
 * портрете.
 */
function avatarOf(m: Mats, v: AssassinAvatar): AvatarSpec {
  const base = { colors: AVATAR_COLORS, skyline: AVATAR_SKYLINE, halo: [52, 4, 19] as const, emblem: { cut: [0.32, -0.3, 0.78] as const, polys: [SKULL], color: '#74397f' } };
  if (v === 'b') return { ...base, draw: (p) => drawAssassin(p, PORTRAIT_B, m), crop: [28, -15, 88] };
  if (v === 'c') return { ...base, draw: (p) => drawAssassin(p, PORTRAIT_C, m), crop: [28, -15, 88] };
  return { ...base, draw: (p) => drawAssassin(p, REST, m), crop: [28, -15, 88] };
}

