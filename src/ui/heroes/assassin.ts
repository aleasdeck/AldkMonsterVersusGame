/**
 * Ассасин пиксельной лепкой — облик A «С листа» (решение пользователя со страницы «Лепка троих»,
 * tools/hero-proto/trio-page.ts): палитра и детали прежнего листа, приглушённые под сцену; красное — шарф, узкий клин
 * набедренной полосы и конец кушака, как на листе. Облики B «Отравитель» и C «Сумрак» — в истории ветки. В игру ещё не
 * входит: записи в `HERO_MODELS` нет, инструменты находят модель по имени файла (`assassinModel()`).
 *
 * Шаг 4 — клипы: девять общих (Тень покрова — клич, Двойной выпад — сильный удар) и личный клип Дымовой шашки
 * «Исчезновение» (`vanish`, решение пользователя вместо клича): шашка под ноги, дым стеной от земли, силуэт растворяется
 * в нём по клеткам и выходит из дыма уже в стойке. Решения пользователя со страницы «Лепка троих»: удар — «Выпад»
 * передней рукой, сильный удар — «Ножницы» (оба клинка разом вперёд, затем рывком врозь), лечение — «Вдох» стоя;
 * смерть — ничком, как у Берсерка (после ревью риггера). Отвергнутые варианты — удар «Снизу», сильный удар «Раз-два», лечение
 * «На колено», падение на спину — и сгиб локтя «пешнёй» для отвергнутых глотка и удара сверху — в истории ветки. Риг
 * правился по двум кругам ревью агента-риггера. Обе руки ведутся кистью; клинки обратным хватом продолжают предплечье —
 * в клипах они идут от предплечья с пределом запястья `WRIST` ±35°. Из этого правило поз: поднятая кисть при обычном
 * сгибе смотрит клинком вверх («факел»), поэтому удары — передней рукой вперёд и ближней ниже шарфа, а не над головой (у
 * ближней руки плечо сзади на высоте маски, и её выпад ложится поперёк лица).
 *
 * Референс — прежний рисованный лист `src/assets/heroes/assassin.png` (один ряд покоя, ячейка 182, фигура первого
 * кадра 164 точки: x 8…177 с остриями клинков, y 10…173). Контуры частей обведены по первому кадру в точках листа и
 * переводятся в единицы поля функциями `X`, `Y`, `S` (k = 120 / 164, левый край фигуры → 4, низ → земля): в коде стоят
 * числа листа, чтобы сверку можно было повторить по сетке (урок Паладина — «анатомия на глаз»).
 *
 * Что на листе: низкая широкая стойка — ближняя нога прямой диагональю уходит влево-назад, дальняя согнута коленом к
 * врагам; верх ссутулен, большой капюшон подан к врагам, лицо — тёмный проём, светлая полоса у глаз, ниже чёрная
 * маска; шарф петлёй вокруг шеи, концы закинуты на ближнее плечо; обе руки висят по бокам почти прямо, предплечья в
 * кожаных обмотках, кулаки держат кинжалы обратным хватом — клинок продолжает линию предплечья вниз и наружу; куртка
 * с полами до колен, пояс с кошелями, спереди красная набедренная полоса; наколенники, голени в обмотках, сапоги.
 *
 * Смотрит вправо, на врагов. Ближняя сторона — левая (рука с кинжалом поверх туловища и полы куртки), дальняя — правая:
 * плечо дальней руки за туловищем, предплечье и второй кинжал — снаружи от корпуса. Свет общий с врагами — сверху слева.
 *
 * Порядок фигур не переставлять без нужды: зерно фактуры движок заводит по порядку, в котором материал встретился в
 * кадре (ловушка «Порядок фигур — это зерно фактуры»).
 */

