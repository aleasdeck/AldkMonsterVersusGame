const BLADE_F = dir(M.armF.hand, P(176, 134));

// ─── Клинки ─────────────────────────────────────────────────────────────────

/**
 * Кинжал обратным хватом — прямой, листовидный, шире у гарды: из-под мизинца кулака наружу и вниз, по линии
 * предплечья. Станции — [s — вдоль клинка от середины кулака, полуширина, сдвиг середины поперёк]; до s ≈ 5 клинок
 * под кулаком.
 */
const DAGGER: Array<[number, number, number]> = [[4, 2, 0], [8.5, 3, 0], [14, 2.9, 0], [21, 2.1, 0], [27, 1, 0], [31, 0, 0]];
/** Длина клинка от середины кулака до острия — конец оружия для зонда. */
const BLADE_LEN = DAGGER[DAGGER.length - 1][0];
/** Свет сцены на плоскости рисунка — сверху слева: по нему выбирается освещённая кромка клинка. */
const LIGHT2 = [-0.49, -0.87];
/**
 * Оси клинка под углом `a`: вдоль и поперёк. Поперечная ось смотрит к врагам (x растёт) — от неё выбирается,
 * какая кромка на свету.
 */
function bladeAxes(a: number): { u: number[]; n: number[] } {
  const side = Math.sin(a * DEG) > 0 ? -1 : 1;
  const b = a * DEG;
  const u = [Math.cos(b), Math.sin(b)];
  const n = [-u[1] * side, u[0] * side];
  return { u, n };
}

function blade(p: Painter, m: Mats, x: number, y: number, a: number, part: string, tone: number): void {
  const { u, n } = bladeAxes(a);
  const q = (s: number, t: number): [number, number] => [x + u[0] * s + n[0] * t, y + u[1] * s + n[1] * t];
  const st = DAGGER;
  const one: number[] = [], two: number[] = [];
  for (const [s, w, c] of st) one.push(...q(s, c + w));
  for (let i = st.length - 1; i >= 0; i--) two.push(...q(st[i][0], st[i][2] - st[i][1]));
  p.poly([...one, ...two], m.blade, { part, bevel: 1, flat: 0.75, lift: 0.6, tone });
  // Кромка к свету — светлая черта по краю; дол — тёмная черта посередине.
  const lit = n[0] * LIGHT2[0] + n[1] * LIGHT2[1] > 0 ? 1 : -1;
  const edge: number[] = [];
  for (let i = 1; i < st.length - 1; i++) edge.push(...q(st[i][0], st[i][2] + lit * (st[i][1] - 0.6)));
  stroke(p, edge, m.edge, part);
  stroke(p, [...q(6, 0), ...q(19, 0)], LOOK.blades[1], part);
  // Гарда — латунная перекладина поперёк.
  p.limb(...q(4, -3.6), 1.1, ...q(4, 3.6), 1.1, m.brass, { part: `${part}Guard`, lift: 0.8, tone });
}

