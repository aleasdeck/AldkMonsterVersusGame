function drawArcher(p: Painter, P: ArcherPose, m: Mats, probe?: HeroProbe): void {
  const breath = p.bob(2, 2);
  const turn = p.blink(0.62, 0.16);
  // Падение на спину: таз к земле и чуть назад, верх ложится назад, головой от врагов.
  const fall = ease(Math.max(0, Math.min(1, P.fall)));
  const bounce = P.fall > 1 ? (P.fall - 1) * 50 : 0;
  const hipX = lerp(PELVIS[0], PELVIS[0] - 4, fall);
  const hipY = lerp(PELVIS[1] + P.crouch, FALL_HIP, fall) - bounce;
  const rot = lerp(P.lean, FALL_ROT, fall) * DEG;
  const up = { dx: hipX - PELVIS[0], dy: hipY - PELVIS[1] - breath * (1 - fall), rot, px: PELVIS[0], py: PELVIS[1] };
  const cr = Math.cos(rot), sr = Math.sin(rot);
  const toWorld = (x: number, y: number): [number, number] =>
    [PELVIS[0] + cr * (x - PELVIS[0]) - sr * (y - PELVIS[1]) + up.dx, PELVIS[1] + sr * (x - PELVIS[0]) + cr * (y - PELVIS[1]) + up.dy];
  const floorY = G - P.y;
  const probeInfo: Record<string, number> = {};

  p.pose({ dx: P.x, dy: P.y }, () => {
    p.shadow(X(92) - P.x * 0.5 - 14 * fall, 54 + 8 * fall, 4);

    // Павший ложится на плащ: полоса плаща на земле под телом растёт с падением (с `fall` 0,35), а плащ за спиной
    // прижимается к земле (ниже — ушёл бы под неё). Выключать плащ разом нельзя: на кадре перехода он исчезал целиком,
    // пока тело ещё было наклонено на 63°.
    const spread = Math.max(0, Math.min(1, (fall - 0.35) / 0.4));
    if (spread > 0) {
      const gp = [-84, 4, -60, 8, -30, 9, 0, 7, 14, 3, 16, 0, -90, 0];
      p.poly(gp.flatMap((v, i) => (i % 2 ? [floorY - v * spread] : [hipX + v * lerp(0.4, 1, spread)])), m.cloak, { part: 'cloakGround', tone: -0.12, bevel: 3 });
    }

    // ── Плащ — за спиной, в повороте верха; верх висит на плечах и дышит с ними, подол стоит и колышется. ──
    {
      const swing = 1.1 * p.wave(1, 0.1);
      const sway = (pts: number[]): number[] => pts.map((v, i) => {
        const y = i % 2 ? v : pts[i + 1];
        const t = Math.max(0, Math.min(1, (y - Y(60)) / (Y(140) - Y(60))));
        return i % 2 ? v + up.dy * (1 - t) : v + (swing - P.cape * 10) * t * t;
      });
      if (fall <= 0) {
        p.pose({ rot, px: PELVIS[0], py: PELVIS[1] }, () => {
          p.poly(sway(cloakOutline()), m.cloak, { part: 'cloak', tone: -0.06, bevel: 5 });
          // Изнанка плаща между ногами — в тени: освещённая, как наружная сторона, она сливала бёдра с плащом в один ком.
          p.poly(sway(S(70, 96, 124, 92, 126, 160, 64, 160)), m.cloak, { part: 'cloak', paint: true, tone: -0.35 });
          for (const f of CLOAK_FOLDS) stroke(p, sway(S(...f)), m.fold, 'cloak');
          for (const f of CLOAK_LIT) stroke(p, sway(S(...f)), m.foldLit, 'cloak');
        });
      } else {
        // Падение: подол, стоявший на месте, идёт за телом (доля `fall`), всё, что ниже земли, ложится на неё и
        // отъезжает назад, к голове павшего.
        const fallen = (pts: number[]): number[] => {
          const sw = sway(pts), out: number[] = [];
          for (let k = 0; k < sw.length; k += 2) {
            const x = sw[k], y = sw[k + 1];
            const t = Math.max(0, Math.min(1, (pts[k + 1] - Y(60)) / (Y(140) - Y(60))));
            const sx = PELVIS[0] + cr * (x - PELVIS[0]) - sr * (y - PELVIS[1]), sy = PELVIS[1] + sr * (x - PELVIS[0]) + cr * (y - PELVIS[1]);
            const [bx, by] = toWorld(x, y - up.dy * (1 - t));
            let wx = lerp(sx, bx, fall), wy = lerp(sy, by, fall);
            if (wy > floorY - 1) {
              wx -= (wy - floorY + 1) * 0.9;
              wy = floorY - 1;
            }
            out.push(wx, wy);
          }
          return out;
        };
        p.poly(fallen(cloakOutline()), m.cloak, { part: 'cloak', tone: -0.06, bevel: 5 });
        p.poly(fallen(S(70, 96, 124, 92, 126, 160, 64, 160)), m.cloak, { part: 'cloak', paint: true, tone: -0.35 });
        for (const f of CLOAK_FOLDS) stroke(p, fallen(S(...f)), m.fold, 'cloak');
        for (const f of CLOAK_LIT) stroke(p, fallen(S(...f)), m.foldLit, 'cloak');
      }
    }

    // ── Колчан за спиной — в позе верха; павший ложится на него (колчан рисуется до торса и уходит под тело). ──
    if (fall <= 0.9) p.pose(up, () => quiver(p, m, P.qpull));

    // Руки, лук и натяжение — до ног: выпавший лук рисуется раньше них.
    const fA = farArm(P), nA = nearArm(P);
    const fa = Math.atan2(fA.hy - fA.ey, fA.hx - fA.ex) / DEG, ua = Math.atan2(fA.ey - fA.sy, fA.ex - fA.sx) / DEG;
    const bowA = P.bow + P.bws * (fa - FORE_F);
    // Натяжение плеч: в покое — само `draw`, в клипах — по оттяжке кисти от рукояти; дрожь тетивы качает и плечи.
    const pull = Math.hypot(nA.hx - fA.hx, nA.hy - fA.hy);
    const bend = lerp(P.draw, P.draw * Math.max(0, Math.min(OVERDRAW, (pull - BRACE) / (FULL_PULL - BRACE))), P.ik) - 0.06 * P.twang;
    let nock: [number, number] = [nA.hx, nA.hy], tip: [number, number] = [0, 0];
    let bowTips: [number, number, number, number] = [0, 0, 0, 0];
    // Выпавший лук (смерть) падает от кулака к земле с ускорением и ложится плашмя верхним концом к врагам, тетивой вверх,
    // стрела соскальзывает и ложится рядом. Лук выпал из дальней руки и лежит с дальней стороны тела — рисуется до ног и
    // верха (урок Берсерка: топор за телом), и павший не закрыт им целиком.
    const drop = ease(Math.max(0, Math.min(1, P.drop)));
    let bowWorld = false;
    if (drop > 0) {
      bowWorld = true;
      const [hwx, hwy] = toWorld(fA.hx, fA.hy);
      const gx = lerp(hwx, BOW_LAND[0] - P.x, drop), gy = lerp(hwy, floorY - BOW_LAND[1], drop * drop);
      const b = bow(p, m, gx, gy, lerp(bowA + rot / DEG, 90, drop), bend * (1 - drop));
      bowTips = [...b.endBot, ...b.endTop];
      const chord: [number, number] = [lerp(b.top[0], b.bot[0], 0.53), lerp(b.top[1], b.bot[1], 0.53)];
      const aOn = Math.atan2(b.rest[1] - chord[1], b.rest[0] - chord[0]) / DEG;
      nock = [lerp(chord[0], ARROW_LAND[0] - P.x, drop), lerp(chord[1], floorY - ARROW_LAND[1], drop * drop)];
      tip = arrow(p, m, nock[0], nock[1], aOn + nrm(-4 - aOn) * drop, P.arrow <= 0.5);
      // Лук лежит за телом — тетива только по пустым клеткам (декаль иначе легла бы поверх голеней).
      p.line(b.top[0], b.top[1], b.bot[0], b.bot[1], m.string, true);
    }

    // ── Ноги: бедро от таза, колено — ik в больших сдвигах (шаг), в малых идёт за тазом и стопой наполовину; стопы
    //    стоят. Штаны темнее плаща, голенище толщиной с лист, высокие сапоги с обмоткой, наколенники. ──
    const legs = [
      { g: M.legF, L2: LEG_F, side: 'far', tone: -0.1, boot: BOOT_F, bend: [1, -0.2], foot: P.footF, lift: P.liftF, out: 1, rt: [10, 8.5, 7.2, 6], pants: m.pantsF },
      { g: M.legN, L2: LEG_N, side: 'near', tone: 0, boot: BOOT_N, bend: [-1, -0.3], foot: P.footN, lift: P.liftN, out: -1, rt: [11, 9, 7.6, 6.2], pants: m.pantsN },
    ] as const;
    // Падая, бёдра поворачиваются вместе с тазом, ноги вытягиваются к врагам и ложатся на землю.
    const legRot = lerp(0, FALL_ROT * DEG, fall);
    for (const lg of legs) {
      const dhx = hipX - PELVIS[0], dhy = hipY - PELVIS[1];
      const ox = lg.g.hip[0] - PELVIS[0], oy = lg.g.hip[1] - PELVIS[1];
      const hx = fall > 0 ? hipX + Math.cos(legRot) * ox - Math.sin(legRot) * oy : lg.g.hip[0] + dhx;
      const hy = fall > 0 ? hipY + Math.sin(legRot) * ox + Math.cos(legRot) * oy : lg.g.hip[1] + dhy;
      const floor = lg.g.ank[1] - P.y;
      const kneel = lg.side === 'near' ? P.kneel : 0, kick = lg.side === 'far' ? P.kick : 0;
      let ax = lg.g.ank[0] + lg.foot - P.x, ay = floor - lg.lift;
      let toe = 0;
      const kneelY = G - P.y - KNEEL_ANKLE;
      if (kneel > 0) {
        // Колено на земле под бедром, голень назад по земле к сапогу, упёртому носком. Стопа остаётся на месте (у листа
        // стойка широкая — щиколотка и так позади бедра на голень): к бедру её тянуло на 10, сапог скользил вперёд.
        ay = lerp(ay, kneelY, kneel);
        toe += KNEEL_TOE * kneel;
      }
      const dax = ax - lg.g.ank[0], day = ay - lg.g.ank[1];
      const big = Math.max(Math.abs(dhy), Math.hypot(dax, day));
      const w = kneel > 0 || fall > 0 ? 1 : Math.max(0, Math.min(1, (big - 3) / 4));
      const reach = lg.L2.l1 + lg.L2.l2 - 0.2;
      if (kick > 0 && Math.hypot(ax - hx, ay - hy) > reach) {
        // Пинок: не достаёт — нога вытянута к цели, а не опущена к земле.
        const d = Math.hypot(ax - hx, ay - hy);
        ax = hx + ((ax - hx) * reach) / d;
        ay = hy + ((ay - hy) * reach) / d;
      } else if (w > 0) [ax, ay] = reachFoot(hx, hy, ax, ay, reach);
      toe += w * Math.max(0, floor - ay - kneel * (floor - kneelY)) / 16 * (1 - kick);
      // Лежит — стопы у земли впереди таза.
      const lie: [number, number] = lg.side === 'far' ? [hipX + 44, G - 7] : [hipX + 38, G - 6];
      ax = lerp(ax, lie[0], fall);
      ay = lerp(ay, lie[1], fall);
      // Колено в стойке смотрит назад-наружу, на земле — вниз-вперёд: сгиб ik по смешанному направлению перескакивал
      // на другую сторону линии бедро — щиколотка (на 40 за кадр). Оба решения — и между ними по `kneel` (как у Берсерка).
      let [ikx, iky] = ik(hx, hy, ax, ay, lg.L2.l1, lg.L2.l2, lerp(lg.bend[0], 0.2, fall), lerp(lg.bend[1], -1, fall));
      if (kneel > 0) {
        const [qx, qy] = ik(hx, hy, ax, ay, lg.L2.l1, lg.L2.l2, lerp(0.3, 0.2, fall), lerp(1, -1, fall));
        ikx = lerp(ikx, qx, kneel);
        iky = lerp(iky, qy, kneel);
      }
      const kx = lerp(lg.g.knee[0] + dax / 2, ikx, w), ky = lerp(lg.g.knee[1] + (dhy + day) / 2, iky, w);
      probeInfo[`${lg.side}KneeX`] = kx + P.x;
      probeInfo[`${lg.side}KneeY`] = ky + P.y;
      probeInfo[`${lg.side}AnkX`] = ax + P.x;
      probeInfo[`${lg.side}AnkY`] = ay + P.y;
      probeInfo[`${lg.side}HipX`] = hx + P.x;
      probeInfo[`${lg.side}HipY`] = hy + P.y;
      if (lg.side === 'far') probeInfo.footF = ax + P.x;
      else probeInfo.footN = ax + P.x;
      const leg = `${lg.side}Leg`, shin = `${lg.side}Shin`, foot = `${lg.side}Foot`, knee = `${lg.side}Knee`;
      const tone = lg.tone;
      p.limb(hx, hy, R(lg.rt[0]), kx, ky, R(lg.rt[1]), lg.pants, { part: leg, tone, flat: 0.3 });
      // Голень: под коленом — штанина, ниже — голенище сапога с обмоткой (решение пользователя: «ботинки поменьше» —
      // сапог до колена с листа был самой крупной формой ног). Верх голенища — светлый отворот.
      const [bx, by] = [lerp(kx, ax, BOOT_TOP), lerp(ky, ay, BOOT_TOP)];
      p.limb(kx, ky, R(lg.rt[1] * 0.9), bx, by, R(lg.rt[2]), lg.pants, { part: leg, tone, flat: 0.3 });
      p.limb(bx, by, R(lg.rt[2]), ax, ay, R(lg.rt[3]), m.boot, { part: shin, tone: tone + 0.06, flat: 0.3 });
      stroke(p, [bx - R(lg.rt[2]) * 0.85, by + 0.8, bx + R(lg.rt[2]) * 0.85, by - 0.4], m.lace, shin);
      // Обмотка наискось: стык и ремень тонами самого сапога, не во всю ширину — чёрно-светлые полосы «зеброй»
      // были самой контрастной деталью фигуры.
      for (const f of [0.4, 0.7]) {
        const [cx, cy] = [lerp(bx, ax, f), lerp(by, ay, f)];
        const r = R(lerp(lg.rt[2], lg.rt[3], f));
        stroke(p, [cx - r * 0.8, cy + 1.2, cx + r * 0.8, cy - 0.8], L.boot[1], shin);
        stroke(p, [cx - r * 0.6, cy - 0.4, cx + r * 0.6, cy - 2], L.boot[3], shin);
      }
      // Сапог: подошва на земле; оторванная пятка — поворот вокруг щиколотки; в пинке — подошвой к врагу; лёжа —
      // носком вверх.
      p.pose({ rot: lerp(lerp(toe * lg.out * 0.9, -1.25, kick), -lg.out * 1.35, fall), px: ax, py: ay }, () => {
        const b: number[] = [];
        // Стопа короче и ниже контура листа (`FOOT_X`, `FOOT_Y`): подошва остаётся на земле, пятка и щиколотка — те же.
        const bp = (x: number, y: number): [number, number] => [ax + R(x * FOOT_X), ay + R(SOLE + (y - SOLE) * FOOT_Y)];
        for (let k = 0; k < lg.boot.length; k += 2) {
          const [x, y] = bp(lg.boot[k], lg.boot[k + 1]);
          b.push(x, toe > 0.02 || kick > 0.02 || fall > 0.02 ? y : Math.min(floorY, y));
        }
        // Стопа без линии о голенище: с ней сапог читался отдельным сабо под «ходулей» голени.
        p.poly(b, m.boot, { part: foot, bevel: 2.6, tone: tone - 0.02, noLine: true });
        // Свет по подъёму к носку, подошва.
        stroke(p, lg.out > 0 ? [...bp(10, 2), ...bp(20, 8.5)] : [...bp(-12, 6), ...bp(-20, 10.5)], m.lace, foot);
        stroke(p, lg.out > 0 ? [...bp(-9, 15.5), ...bp(22, 15.5)] : [...bp(-20, 15.5), ...bp(8, 15.5)], m.seam, foot);
      });
      // Отворот сапога под коленом и наколенник — кожаная чашка.
      p.ellipse(kx + R(lg.out > 0 ? 1 : 0), ky, R(lg.out > 0 ? 7 : 7.4), R(lg.out > 0 ? 6 : 6.4), m.knee, { part: knee, lift: 0.6, flat: 0.45, tone: tone + 0.1 });
      stroke(p, [kx - R(4.5), ky + R(3.8), kx + R(4.5), ky + R(3.4)], m.seam, knee);
    }

    // ── Верх: дыхание поднимает грудь, плечи, голову; наклон — в клипах. ──
    p.pose(up, () => {
      // Рука с луком — за туловищем у плеча, вытянута к врагам: рукав, наруч, лук, кулак на рукояти.
      p.limb(fA.sx, fA.sy, R(7), fA.ex, fA.ey, R(6.2), m.armF, { part: 'farArm', tone: -0.12 });
      p.limb(fA.ex, fA.ey, R(6.2), fA.hx, fA.hy, R(5.2), m.armF, { part: 'farArm', tone: -0.1 });
      p.limb(...at(fA.ex, fA.ey, fa, R(8)), R(6.4), ...at(fA.hx, fA.hy, fa, -R(4)), R(5.6), m.bracer, { part: 'farBracer', tone: -0.06 });
      for (const f of [0.35, 0.6, 0.85]) {
        const [cx, cy] = at(fA.ex, fA.ey, fa, lerp(R(8), len([fA.ex, fA.ey], [fA.hx, fA.hy]) - R(4), f));
        stroke(p, [...at(cx, cy, fa - 90, R(5.5)), ...at(cx, cy, fa + 90, R(5))], m.seam, 'farBracer');
      }
      stroke(p, [...at(fA.sx, fA.sy, ua - 90, R(5)), ...at(fA.ex, fA.ey, ua - 90, R(5))], m.lace, 'farArm');
      const b = bowWorld ? null : bow(p, m, fA.hx, fA.hy, bowA, bend);
      if (b) bowTips = [...b.endBot, ...b.endTop];
      p.ellipse(fA.hx, fA.hy, R(5.6), R(5), m.hand, { part: 'fistF', lift: 1, tone: -0.08, rot: (fa + 90) * DEG });
      stroke(p, [fA.hx - R(1), fA.hy - R(3.5), fA.hx - R(1), fA.hy + R(3.5)], L.skin[1], 'fistF');

      // Туловище: кожаная куртка, перевязь колчана наискось, шнуровка.
      // Грудь к свету — вверху слева, под тянущей рукой — тень от неё, дальний бок в тени; талия уже плеч.
      p.poly(S(65, 62, 76, 56, 88, 54, 100, 54, 112, 56, 120, 61, 123, 69, 121, 79, 116, 88, 100, 90, 82, 90, 70, 88, 65, 76), m.torso, { part: 'torso', bevel: 5, lift: 1 });
      p.ellipse(X(88), Y(71), R(17), R(11), m.torso, { part: 'torso', lift: 2.2, flat: 0.45, tone: 0.05 });
      // Тень под тянущей рукой — клином под предплечьем, а не полосой во всю грудь (стопка полос читалась бочкой с
      // обручами); ближний бок в тени — торс круглится.
      p.poly(S(78, 67, 119, 66.5, 113, 72.5, 86, 72.5), m.torso, { part: 'torso', paint: true, tone: -0.3 });
      p.poly(S(63, 62, 70, 60, 70, 90, 64, 90), m.torso, { part: 'torso', paint: true, tone: -0.24 });
      p.poly(S(76, 58, 82, 56, 124, 80, 121, 85), m.belt, { part: 'torso', paint: true });
      stroke(p, S(80, 57, 123, 81), m.lace, 'torso');
      stroke(p, S(99, 74, 99, 87), m.seam, 'torso');
      for (const y of [77, 82]) stroke(p, S(97, y, 101, y + 1), m.lace, 'torso');
      p.poly(S(113, 64, 123, 70, 121, 80, 116, 88, 111, 88), m.torso, { part: 'torso', paint: true, tone: -0.42 });

      // Полоса ткани спереди — из-под пояса до голени, рваный конец; на выпаде относит назад.
      // Присел ниже, чем достаёт полоса, — она ложится складками на землю (сжимается от бедра), а не уходит под неё.
      const tf = P.cape * 5;
      const fold = (G - 1 - (hipY - PELVIS[1]) - Y(112)) / (Y(161) - Y(112));
      const tb = fold < 1 ? (pts: number[]): number[] => pts.map((v, i) => (i % 2 && v > Y(112) ? Y(112) + (v - Y(112)) * Math.max(0.3, fold) : v)) : (pts: number[]): number[] => pts;
      p.poly(tb(S(85, 93, 105, 93, 107, 112, 104 - tf * 0.5, 132, 99 - tf, 150, 95 - tf, 161, 90 - tf, 150, 87 - tf * 0.5, 133, 83, 112)), m.tabard, { part: 'tabard', bevel: 2.4 });
      stroke(p, tb(S(91, 98, 90 - tf, 140)), m.fold, 'tabard');
      stroke(p, tb(S(99, 98, 99 - tf, 142)), m.fold, 'tabard');
      // Сумка на ближнем боку и клапан на дальнем.
      p.poly(S(64, 90, 79, 91, 80, 102, 73, 106, 65, 103), m.pouch, { part: 'pouch', bevel: 2 });
      p.poly(S(64, 90, 79, 91, 79.5, 96, 64.5, 95.5), m.pouch, { part: 'pouch', paint: true, tone: -0.22 });
      p.px(X(72), Y(96.5), L.steel[3]);
      p.poly(S(104, 91, 117, 90, 119, 101, 111, 105, 105, 101), m.pouch, { part: 'flapF', bevel: 2, tone: -0.14 });
      // Пояс и круглая пряжка.
      p.poly(S(64, 84.5, 90, 85.5, 117, 84, 118, 91.5, 90, 93, 64, 92.5), m.belt, { part: 'belt', bevel: 1.4 });
      stroke(p, S(65, 86, 90, 87, 116, 85.5), m.lace, 'belt');
      p.ellipse(X(95), Y(89), R(4), R(4), m.buckle, { part: 'buckle', lift: 1 });
      p.ellipse(X(95), Y(89), R(1.8), R(1.8), m.dark, { part: 'buckle', paint: true });

      // Пелерина и голова: голова раз за цикл подаётся к прицелу на пиксель — сдвигом, не поворотом: поворот на 1–2°
      // перерисовывал мелкое лицо и оно мигало.
      mantle(p, m);
      p.pose({ dx: p.snap(1.5 * turn), rot: P.head * DEG, px: M.neck[0], py: M.neck[1] }, () =>
        p.scope(HEAD_SCALE, M.neck[0] * (1 - HEAD_SCALE), M.neck[1] * (1 - HEAD_SCALE), () => head(p, m)));

      // Стрела — на тетиве: от ушка у тянущей кисти к полке над кулаком; в руке — через кулак под углом `aa`. Поверх
      // руки с луком и груди, под тянущей рукой. Выпавший лук со стрелой нарисован раньше, до ног.
      const chord: [number, number] = b ? [lerp(b.top[0], b.bot[0], 0.53), lerp(b.top[1], b.bot[1], 0.53)] : [0, 0];
      let onString: [number, number] = chord;
      if (b) {
        if (P.twang) {
          // Дрожь тетивы — поперёк хорды, к луку и от него.
          const cx = b.bot[0] - b.top[0], cy = b.bot[1] - b.top[1], cl = Math.hypot(cx, cy) || 1;
          let nx = -cy / cl, ny = cx / cl;
          if ((fA.hx - chord[0]) * nx + (fA.hy - chord[1]) * ny < 0) [nx, ny] = [-nx, -ny];
          chord[0] += nx * P.twang;
          chord[1] += ny * P.twang;
        }
        onString = [lerp(chord[0], nA.hx - R(1.5), P.draw), lerp(chord[1], nA.hy, P.draw)];
        const aOn = Math.atan2(b.rest[1] - onString[1], b.rest[0] - onString[0]) / DEG;
        const inHand: [number, number] = at(nA.hx, nA.hy, P.aa, -P.agrip);
        nock = P.nocked >= 1 ? onString : [lerp(inHand[0], onString[0], P.nocked), lerp(inHand[1], onString[1], P.nocked)];
        const aa = P.nocked >= 1 ? aOn : P.nocked <= 0 ? P.aa : P.aa + nrm(aOn - P.aa) * P.nocked;
        tip = arrow(p, m, nock[0], nock[1], aa, P.arrow <= 0.5);
      }

      // Тянущая рука — поверх груди: рукав до локтя, голый локоть, наруч, кисть у тетивы.
      const na = Math.atan2(nA.hy - nA.ey, nA.hx - nA.ex) / DEG;
      p.limb(nA.sx, nA.sy, R(7.2), nA.ex, nA.ey, R(6.4), m.armN, { part: 'nearArm' });
      p.ellipse(nA.ex + R(1), nA.ey, R(5.6), R(5.2), m.elbow, { part: 'nearArm', lift: 1.2 });
      p.limb(...at(nA.ex, nA.ey, na, R(6)), R(6.2), ...at(nA.hx, nA.hy, na, -R(3)), R(5), m.bracer, { part: 'nearBracer' });
      for (const f of [0.3, 0.55, 0.8]) {
        const [cx, cy] = at(nA.ex, nA.ey, na, lerp(R(6), len([nA.ex, nA.ey], [nA.hx, nA.hy]) - R(3), f));
        stroke(p, [...at(cx, cy, na - 90, R(5.5)), ...at(cx, cy, na + 90, R(5))], m.seam, 'nearBracer');
      }
      stroke(p, [...at(nA.ex, nA.ey, na - 90, R(5)), ...at(nA.hx, nA.hy, na - 90, R(4.5))], m.lace, 'nearBracer');
      p.ellipse(nA.hx, nA.hy, R(5.2), R(4.8), m.hand, { part: 'fistN', lift: 1, tone: 0.1 });
      stroke(p, [nA.hx - R(2), nA.hy - R(1), nA.hx + R(2.5), nA.hy + R(1)], L.skin[1], 'fistN');
      // Склянка в кулаке — поверх пальцев: горлышко к `fla`, донце за кулаком; стекло цвета зелья с бликом, пробка.
      if (P.flask > 0.5) {
        const [bx, by] = at(nA.hx, nA.hy, P.fla, -R(1));
        p.ellipse(bx, by, R(6), R(4.6), FLASK, { part: 'flask', lift: 2, rot: P.fla * DEG });
        p.limb(...at(bx, by, P.fla, R(4.5)), R(2.2), ...at(bx, by, P.fla, R(9)), R(1.9), FLASK, { part: 'flask', tone: 0.12 });
        p.ellipse(...at(bx, by, P.fla, R(10)), R(2.2), R(2), CORK, { part: 'cork', lift: 0.5 });
        p.px(...at(...at(bx, by, P.fla, -R(1.5)), P.fla - 90, R(2.5)), '#f4c8c0');
      }

      // Тетива — линия в пиксель поверх всего: от узлов на концах плеч к ушку стрелы, но обрывается на краю кулака —
      // линия поверх всего резала тянущую кисть, самое светлое пятно у тетивы на листе.
      if (b) {
        const [sx, sy] = P.draw > 0.02 ? onString : chord;
        const cut = P.draw > 0.02 ? R(7) : 0;
        const edge = (tx: number, ty: number): [number, number] => {
          const l = Math.hypot(tx - sx, ty - sy) || 1;
          return [sx + ((tx - sx) / l) * cut, sy + ((ty - sy) / l) * cut];
        };
        // Тетива — декаль, она ложится поверх всего кадра, где бы ни была вызвана. Спущенная тетива лука, задранного
        // или опущенного больше чем на 45° (клич: лук над головой за капюшоном), — только по пустым клеткам, иначе
        // белая черта шла через лицо.
        // Натянутая тетива лука, заваленного назад больше чем на 30° (урон), — верхний отрезок тоже по пустым клеткам:
        // верхнее плечо уходит за капюшон, а тетива ложилась поверх козырька.
        const tilt = nrm(bowA + rot / DEG);
        const behind = P.draw <= 0.02 && Math.abs(tilt) > 45;
        p.line(b.top[0], b.top[1], ...edge(b.top[0], b.top[1]), m.string, behind || tilt < -30);
        p.line(...edge(b.bot[0], b.bot[1]), b.bot[0], b.bot[1], m.string, behind);
      }

      // Блик на наконечнике — прицел (приём): свечение и крестик в пиксель.
      if (b && P.glint > 0.05 && P.arrow > 0.5) {
        p.glow(tip[0], tip[1], 5 + 6 * P.glint, '#ffe0a0', 0.5 * P.glint);
        const r = P.glint > 0.5 ? 4.5 : 3;
        for (let k = -r; k <= r; k += 1.5) {
          p.px(tip[0] + k, tip[1], Math.abs(k) < 2 ? '#fffbe8' : '#ffe8a8');
          p.px(tip[0], tip[1] + k, Math.abs(k) < 2 ? '#fffbe8' : '#ffe8a8');
        }
      }
    });

    if (probe?.on) {
      const W = (x: number, y: number): [number, number] => {
        const [wx, wy] = toWorld(x, y);
        return [wx + P.x, wy + P.y];
      };
      const [hwx, hwy] = W(fA.hx, fA.hy), [swx, swy] = W(fA.sx, fA.sy), [ewx, ewy] = W(fA.ex, fA.ey);
      // Выпавший лук и стрела нарисованы в кадре, а не в верхе.
      const B = (x: number, y: number): [number, number] => (bowWorld ? [x + P.x, y + P.y] : W(x, y));
      const [twx, twy] = B(bowTips[0], bowTips[1]), [bwx, bwy] = B(bowTips[2], bowTips[3]);
      const [nhx, nhy] = W(nA.hx, nA.hy), [nex, ney] = W(nA.ex, nA.ey), [nsx, nsy] = W(nA.sx, nA.sy);
      const [awx, awy] = B(...tip), [kwx, kwy] = B(...nock);
      // Запястье — ось лука вверх от рукояти (270 + наклон) к предплечью; локоть — угол между плечом и предплечьем.
      const wrist = nrm(270 + bowA - fa), elbow = 180 - Math.abs(nrm(fa - ua));
      // Тянущая рука: плечо в ракурсе короче настоящего (≈ 20, как у руки с луком) — сгиб с поправкой на глубину.
      const ux = nA.ex - nA.sx, uy = nA.ey - nA.sy, uz = Math.sqrt(Math.max(0, ARM_F.l1 ** 2 - ux * ux - uy * uy));
      const fx = nA.hx - nA.ex, fy = nA.hy - nA.ey;
      const nElbow = Math.acos(Math.max(-1, Math.min(1, (-ux * fx - uy * fy) / (Math.hypot(ux, uy, uz) * Math.hypot(fx, fy) || 1)))) / DEG;
      const nElbow2d = 180 - Math.abs(nrm(Math.atan2(fy, fx) / DEG - Math.atan2(uy, ux) / DEG));
      probe.on({
        ...probeInfo, hipX: hipX + P.x, hipY: hipY + P.y, handX: hwx, handY: hwy, tipX: twx, tipY: twy, ground: G, wrist, elbow,
        shX: swx, shY: swy, elX: ewx, elY: ewy, butX: bwx, butY: bwy,
        nHandX: nhx, nHandY: nhy, nElX: nex, nElY: ney, nShX: nsx, nShY: nsy, nElbow, nElbow2d,
        arrowX: awx, arrowY: awy, nockX: kwx, nockY: kwy, arrow: P.arrow > 0.5 ? 1 : 0,
      });
    }
  });
}
