// ─── Рваный край ────────────────────────────────────────────────────────────

/**
 * Рваный край ткани: ломаная (единицы поля) с зубцами — между вершинами через `step` торчит зубец на `amp` по нормали
 * (`side` 1 — налево от хода на экране), кончик отнесён вдоль хода на `lean`; длина зубцов гуляет 1 / 0,55 / 0,8
 * (как мех Берсерка — `furEdge`).
 */
function ragEdge(pts: number[], amp: number, step: number, side: 1 | -1, lean = 0): number[] {
  const out: number[] = [];
  let k = 0;
  for (let i = 0; i + 3 < pts.length; i += 2) {
    const x0 = pts[i], y0 = pts[i + 1], x1 = pts[i + 2], y1 = pts[i + 3];
    const l = Math.hypot(x1 - x0, y1 - y0) || 1;
    const tx = (x1 - x0) / l, ty = (y1 - y0) / l;
    const nx = ty * side, ny = -tx * side;
    const n = Math.max(1, Math.round(l / step));
    for (let j = 0; j < n; j++) {
      const a = j / n, b = (j + 0.5) / n, s = [1, 0.55, 0.8][k++ % 3];
      out.push(x0 + (x1 - x0) * a, y0 + (y1 - y0) * a);
      out.push(x0 + (x1 - x0) * b + nx * amp * s + tx * lean, y0 + (y1 - y0) * b + ny * amp * s + ty * lean);
    }
  }
  out.push(pts[pts.length - 2], pts[pts.length - 1]);
  return out;
}

// ─── Лук ────────────────────────────────────────────────────────────────────

/**
 * Лук в координатах от рукояти (точки листа: dx — вперёд, к врагам, dy — вниз; радиус — в единицах) при полном
 * натяжении, как на листе: рекурсивный, плечи дугой к лучнику, концы загнуты вперёд, обмотки у рукояти. Разогнутый лук
 * (натяжение 0) — плечи отходят вперёд на `relax` точек листа к концам (квадрат расстояния от рукояти). Узлы тетивы —
 * на брюшке концов плеч; `wraps` — обмотки поперёк плеча.
 */
const BOW = {
  upper: [[0, -7, 2.1], [-1.5, -17, 1.9], [-5, -27, 1.75], [-9.5, -37, 1.6], [-13.5, -47, 1.45], [-16.5, -56, 1.3], [-18, -63, 1.15], [-17.5, -67.5, 1.05], [-14.5, -69.5, 1]] as Array<[number, number, number]>,
  lower: [[0, 7, 2.1], [-3, 17, 1.9], [-7, 27, 1.75], [-12.5, 37, 1.6], [-16.5, 46, 1.45], [-19, 52, 1.3], [-19.5, 56, 1.15], [-17.5, 58.5, 1]] as Array<[number, number, number]>,
  nockU: [-19.5, -62] as [number, number],
  nockL: [-21, 53] as [number, number],
  relax: 6,
  wraps: [-13, 12],
};

/**
 * Точки лука в кадре: рукоять (gx, gy), наклон `a` (градусы, плюс — верхний конец к врагам), натяжение плеч `bend`
 * (1 — как на листе, 0 — разогнуты; больше 1 — перетянуты, в клипе выстрела и ниже 0 — дрожат после спуска).
 */
function bowFrame(gx: number, gy: number, a: number, bend: number): (dx: number, dy: number) => [number, number] {
  const c = Math.cos(a * DEG), s = Math.sin(a * DEG);
  return (dx, dy) => {
    const f = (1 - bend) * BOW.relax * (dy / 70) ** 2;
    const x = R(dx + f), y = R(dy);
    return [gx + x * c - y * s, gy + x * s + y * c];
  };
}

/** Лук: плечи одной частью, обмотки краской; отдаёт узлы тетивы, полку для стрелы (над кулаком) и концы плеч (зонд). */
function bow(p: Painter, m: Mats, gx: number, gy: number, a: number, bend: number): { top: [number, number]; bot: [number, number]; rest: [number, number]; endTop: [number, number]; endBot: [number, number] } {
  const q = bowFrame(gx, gy, a, bend);
  const chain = (pts: Array<[number, number, number]>): Array<[number, number, number]> => pts.map(([dx, dy, r]) => [...q(dx, dy), r] as [number, number, number]);
  const grip: Array<[number, number, number]> = [[0, 0, 2.3]];
  p.chain([...chain([...BOW.upper].reverse()), ...chain(grip), ...chain(BOW.lower)], m.wood, { part: 'bow' });
  // Обмотка рукояти и обмотки плеч.
  p.limb(...q(0, -8), 2.6, ...q(0, 8), 2.6, m.grip, { part: 'bow', paint: true });
  for (const dy of BOW.wraps) {
    const [x0, y0] = q(-5, dy), [x1, y1] = q(4, dy);
    stroke(p, [x0, y0, x1, y1], m.lace, 'bow');
  }
  const endU = BOW.upper[BOW.upper.length - 1], endL = BOW.lower[BOW.lower.length - 1];
  return { top: q(...BOW.nockU), bot: q(...BOW.nockL), rest: q(-1.5, -8.5), endTop: q(endU[0], endU[1]), endBot: q(endL[0], endL[1]) };
}

/** Длина стрелы от ушка до острия. */
const ARROW = R(65);

/**
 * Стрела от ушка (x, y) под углом `a`: древко, оперение у ушка (два пера — вверх и вниз), наконечник. На тетиве ушко
 * закрывает тянущая кисть — оперение видно правее неё.
 */
function arrow(p: Painter, m: Mats, x: number, y: number, a: number, ghost = false): [number, number] {
  const [tx, ty] = at(x, y, a, ARROW);
  const u: [number, number] = [Math.cos(a * DEG), Math.sin(a * DEG)], n: [number, number] = [-u[1], u[0]];
  // Стрелы нет (улетела) — те же фигуры пустыми, за краем кадра краской по пустой части: зерно фактуры идёт по номеру
  // фигуры в кадре, и без них крапинки тянущей руки перебрасывались бы в кадрах без стрелы.
  const off = ghost ? -4000 : 0;
  const o = <T extends object>(s: T): T => (ghost ? { ...s, paint: true } : s);
  const pt = (s: number, t: number): [number, number] => [x + u[0] * s + n[0] * t + off, y + u[1] * s + n[1] * t];
  p.limb(...pt(0.5, 0), 0.8, ...pt(ARROW - 4.5, 0), 0.8, m.arrow, o({ part: 'arrow' }));
  for (const side of [-1, 1]) p.poly([...pt(3.5, 0.4 * side), ...pt(5.5, 2.6 * side), ...pt(11.5, 2.2 * side), ...pt(13, 0.4 * side)], m.fletch, o({ part: 'arrowFletch', bevel: 0.6 }));
  p.poly([...pt(ARROW - 6, 0.9), ...pt(ARROW - 5.5, 2.3), tx + off, ty, ...pt(ARROW - 5.5, -2.3), ...pt(ARROW - 6, -0.9)], m.head, o({ part: 'arrowHead', bevel: 0.8 }));
  return [tx, ty];
}

// ─── Колчан ─────────────────────────────────────────────────────────────────

/**
 * Колчан за спиной: устье под кромкой пелерины над ближним плечом, дно за туловищем; над плечом — перья и древки
 * (устье над пелериной давало бурый ком, из которого прямо росли перья: «кулак с перьями»). Стрелы — [ушко x, y, точка
 * в устье x, y] в точках листа; оперение — лист вдоль древка.
 */
const QUIVER = {
  body: [53, 57, 63, 48, 75, 44, 81, 49, 92, 78, 82, 84],
  mouth: [67, 50],
  arrows: [[33, 28, 59, 52], [41, 20, 63, 51], [50, 15, 67, 50], [59, 13, 71, 49]],
};

/**
 * Перезарядка: ближняя к зрителю стрела колчана (последняя) вытянута вдоль своего древка на `pull` точек листа —
 * тянущая кисть держит её под оперением (`QGRIP`). Стрела остаётся в слое колчана, за торсом: над плечом видно
 * оперение и кусок древка, как у соседних.
 */
const QPULL = 16;
const QGRIP: [number, number] = (() => {
  const [x, y, mx, my] = QUIVER.arrows[QUIVER.arrows.length - 1];
  const l = Math.hypot(mx - x, my - y), ux = (mx - x) / l, uy = (my - y) / l;
  return [X(x - ux * QPULL + ux * 22), Y(y - uy * QPULL + uy * 22)];
})();

/**
 * Каждая стрела — своя часть: между перьями соседних стрел движок кладёт тёмную линию, и оперение читается пучком
 * отдельных перьев, а не серым комом; опахало от света — в тени (одна светлая плашка читалась буквой, а не пером).
 */
function quiver(p: Painter, m: Mats, pull = 0): void {
  p.poly(S(...QUIVER.body), m.quiver, { part: 'quiver', bevel: 3, tone: -0.08 });
  p.ellipse(X(QUIVER.mouth[0]), Y(QUIVER.mouth[1]), R(8.5), R(4), m.quiver, { part: 'quiver', rot: 0.62, lift: 1, tone: -0.25 });
  const fl = 19, fw = 2.6;
  QUIVER.arrows.forEach(([x0, y0, mx, my], k) => {
    let x = x0, y = y0, l = Math.hypot(mx - x, my - y);
    const u = [(mx - x) / l, (my - y) / l], nn = [-u[1], u[0]];
    if (pull > 0 && k === QUIVER.arrows.length - 1) {
      x -= u[0] * pull;
      y -= u[1] * pull;
      l += pull;
    }
    const pt = (s: number, t: number): [number, number] => [X(x + u[0] * s + nn[0] * t), Y(y + u[1] * s + nn[1] * t)];
    const part = `qArrow${k}`;
    p.limb(...pt(fl - 2, 0), R(0.9), ...pt(l, 0), R(0.9), m.shaftQ, { part });
    // Перо: срез у ушка, шире всего у верха, к древку сходится остриём (тупое короткое перо читалось корзиной).
    p.poly([...pt(0.5, fw * 0.6), ...pt(3, fw), ...pt(fl * 0.6, fw * 0.85), ...pt(fl, 0), ...pt(fl * 0.6, -fw * 0.85), ...pt(3, -fw), ...pt(0.5, -fw * 0.6)], m.fletch, { part, bevel: 0.8 });
    // Опахало от света — в тени: перо читается пером, а не плашкой.
    p.poly([...pt(0.5, 0), ...pt(fl, 0), ...pt(fl * 0.6, fw * 0.95), ...pt(3, fw * 1.1), ...pt(0.5, fw * 0.7)], m.fletch, { part, paint: true, tone: -0.28 });
  });
}

