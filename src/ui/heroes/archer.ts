/**
 * Рука в покое — подобие стойки: локоть ставится так, как стоял относительно отрезка плечо — кисть в мерке. Кисть в
 * покое ходит на пиксель-два, а ik на почти прямой (рука с луком) или сложенной (тянущая) руке переводил бы это в
 * прыжки локтя на несколько единиц.
 */
function holdArm(sh: readonly number[], el: readonly number[], hand: readonly number[], hx: number, hy: number): { ex: number; ey: number } {
  const ax = hand[0] - sh[0], ay = hand[1] - sh[1];
  const bx = hx - sh[0], by = hy - sh[1];
  const d = ax * ax + ay * ay;
  // Комплексное отношение (b / a): поворот и масштаб отрезка плечо — кисть.
  const re = (bx * ax + by * ay) / d, im = (by * ax - bx * ay) / d;
  const ex = el[0] - sh[0], ey = el[1] - sh[1];
  return { ex: sh[0] + ex * re - ey * im, ey: sh[1] + ex * im + ey * re };
}

interface Arm { sx: number; sy: number; ex: number; ey: number; hx: number; hy: number }

/**
 * Рука кистью в точке (hx, hy): в покое — форма стойки (`holdArm`), в клипах — ik, локоть из двух решений — то, что
 * ближе к направлению `pref` в координатах верха (тянущая рука — назад и чуть вверх: в стойке локоть отведён назад, у
 * бедра рука висит локтем назад; рука с луком — вниз), кисть не дальше длины руки. Сторону от линии плечо — кисть
 * брать нельзя: у кисти, опущенной к бедру, «вверх-назад от линии» — это вперёд, и локоть тянущей руки вставал у лица
 * («куриное крыло»). Плечевой сустав ходит за рукой: кисть выше плеча поднимает его до 3 единиц. Кисть ближе, чем
 * позволяет длинное предплечье, — оно уходит в глубину и короче в ракурсе (иначе ik не сгибал бы руку).
 */
function solveArm(g: { sh: readonly number[]; el: readonly number[]; hand: readonly number[] }, ik1: number, hx: number, hy: number, o: { dx: number; dy: number; l1: number; l2: number; k1: number; k2: number; pref: readonly [number, number] }): Arm {
  if (ik1 <= 0) {
    const hold = holdArm(g.sh, g.el, g.hand, hx, hy);
    return { sx: g.sh[0], sy: g.sh[1], ex: hold.ex, ey: hold.ey, hx, hy };
  }
  const lift = Math.max(0, Math.min(1, (g.sh[1] - hy - 10) / 30));
  const sx = g.sh[0] + ik1 * o.dx, sy = g.sh[1] + ik1 * (o.dy - 3 * lift);
  // Форма стойки от сдвинутого плеча.
  const hold = holdArm([sx, sy], [g.el[0] + sx - g.sh[0], g.el[1] + sy - g.sh[1]], [g.hand[0] + sx - g.sh[0], g.hand[1] + sy - g.sh[1]], hx, hy);
  let tx = hx, ty = hy;
  const vx = tx - sx, vy = ty - sy, d = Math.hypot(vx, vy) || 1;
  const reach = o.l1 + o.l2 - 0.05;
  if (d > reach) {
    tx = sx + (vx * reach) / d;
    ty = sy + (vy * reach) / d;
  }
  const l2 = Math.min(o.l2, Math.min(d, reach) + o.l1 * 0.9);
  const [ex, ey] = ik(sx, sy, tx, ty, o.l1, l2, o.pref[0], o.pref[1]);
  // Кисть у своего места в стойке (расстояние до плеча то же ±12 %, звенья не менялись) — форма стойки: на почти прямой
  // руке с луком ik переводит сдвиг кисти на единицу в 10° сгиба локтя, и на стыке с покоем локоть прыгал бы.
  const d0 = len(g.sh, g.hand);
  const w = ik1 * Math.max(0, Math.min(1, Math.max(Math.abs(d / d0 - 1) / 0.12, Math.abs(o.k1 - 1) / 0.2, Math.abs(o.k2 - 1) / 0.2)));
  return { sx, sy, ex: lerp(hold.ex, ex, w), ey: lerp(hold.ey, ey, w), hx: lerp(hx, tx, w), hy: lerp(hy, ty, w) };
}

const nearArm = (P: ArcherPose): Arm => solveArm(M.armN, P.ik, P.nhx, P.nhy, { dx: P.nsx, dy: P.nsy, l1: ARM_N.l1 * P.nl, l2: ARM_N.l2 * P.nf, k1: P.nl, k2: P.nf, pref: [Math.cos(P.nel * DEG), Math.sin(P.nel * DEG)] });
const farArm = (P: ArcherPose): Arm => solveArm(M.armF, P.ik, P.fhx, P.fhy, { dx: P.fsx, dy: P.fsy, l1: ARM_F.l1 * P.fl, l2: ARM_F.l2 * P.fl, k1: P.fl, k2: P.fl, pref: [Math.cos(P.fel * DEG), Math.sin(P.fel * DEG)] });

const nrm = (a: number): number => { a = ((a % 360) + 360) % 360; return a > 180 ? a - 360 : a; };

/**
 * Покой: лучник держит натяжение — грудь дышит на пиксель, таз оседает на четверть цикла позже, раз за цикл вес
 * переходит с ноги на ногу; стопы стоят, колени в малых сдвигах идут за тазом наполовину (урок Паладина). Кисти
 * повторяют 40 % движения корпуса — лук и тетива держат прицел, а не качаются с грудью одним блоком; лук чуть
 * покачивается с запаздыванием, плащ колышется.
 */
function idlePose(p: Painter): ArcherPose {
  const P = { ...REST };
  P.crouch += p.bob(1.5, 2, 0.25);
  P.x += p.snap(1.2 * p.wave(1, 0.3));
  const bodyX = P.x, bodyY = P.crouch - p.bob(2, 2);
  P.nhx -= 0.6 * bodyX;
  P.nhy -= 0.6 * bodyY;
  P.fhx -= 0.6 * bodyX;
  P.fhy -= 0.6 * bodyY;
  P.bow += 1.2 * p.wave(1, 0.45);
  return P;
}

/**
 * Ключ — снимок позы: поле, которого в ключе нет, держит значение прошлого ключа (до первого — покоя). У `poseAt`
 * поле без ключа тянется между своими ключами через чужие: `nl` 1,9 на кадре спуска растягивало плечо уже в кадре
 * добора, `arrow` 0 прятал стрелу за кадр до спуска. Здесь каждое поле меняется только между соседними ключами.
 */
function fillKeys(keys: PoseKeys<ArcherPose>, base: ArcherPose): PoseKeys<ArcherPose> {
  const fields = new Set<string>();
  for (const [, k] of keys) for (const f of Object.keys(k)) fields.add(f);
  const cur: Record<string, number> = {};
  for (const f of fields) cur[f] = base[f];
  return keys.map(([n, k]) => {
    for (const f of fields) if (k[f] !== undefined) cur[f] = k[f] as number;
    return [n, { ...cur } as Partial<ArcherPose>];
  });
}

/** Поза кадра: ключи клипа поверх покоя в фазе 0 или сам покой. */
function framePose(p: Painter, clips: Partial<Record<ArcherClip, PoseKeys<ArcherPose>>>): ArcherPose {
  const base = idlePose(p);
  const c = clipAt(p);
  if (c) {
    const keys = clips[c.clip as ArcherClip];
    return keys ? poseAt(base, fillKeys(keys, base), c.f, c.n, HERO_CLIPS[c.clip].hold) : base;
  }
  base.cape += 0.05 * (1 - Math.cos(2 * Math.PI * p.t));
  return base;
}

