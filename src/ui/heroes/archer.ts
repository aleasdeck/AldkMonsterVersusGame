const toHead = (x: number, y: number): [number, number] => [M.neck[0] + (x - M.neck[0]) * HEAD_SCALE, M.neck[1] + (y - M.neck[1]) * HEAD_SCALE];
const LEG_N = { l1: len(M.legN.hip, M.legN.knee), l2: len(M.legN.knee, M.legN.ank) };
