/**
 * Сапоги — контуры листа от щиколотки (разница в точках листа). Ближний носком наружу (влево) и в ракурсе короче,
 * дальний — носком к врагам, длинный.
 */
const BOOT_N = [13, -10, 14, 0, 13, 8, 11, 13, -19, 13, -21, 9, -19, 4, -13, 0, -6, -3, -2, -9];
const BOOT_F = [-13, -11, 5, -11, 8, -6, 16, -2, 24, 1, 30, 5, 32, 10, 31, 13, -13, 13, -15, 6, -14, -4];
/**
 * Колено на земле: сапог встаёт на носок — поворот `KNEEL_TOE` (доля, как `toe`: угол 0,9·toe радиана, носком вниз), а
 * щиколотка поднята ровно на низ повёрнутого сапога (`kneelAnkle`), и носок касается земли. Щиколотка на `R(9)` над
 * землёй (голень плашмя) с тем же поворотом уводила носок ближнего сапога на 9 единиц под землю, дальнего — на 13.
 */
const KNEEL_TOE = 0.6;
function kneelAnkle(boot: readonly number[], out: number): number {
  const a = KNEEL_TOE * 0.9 * out, c = Math.cos(a), s = Math.sin(a);
  let low = 0;
  for (let k = 0; k < boot.length; k += 2) low = Math.max(low, R(boot[k]) * s + R(boot[k + 1]) * c);
  return low;
}
const KNEEL_ANKLE = { far: kneelAnkle(BOOT_F, 1), near: kneelAnkle(BOOT_N, -1) };

/** Верхний край горба (точки листа) — от шлема к левому краю; по нему — зубцы прядей. */
const MANTLE_TOP = [108, 28, 104, 23, 97, 21, 90, 20, 83, 21, 75, 21, 66, 23, 57, 26, 50, 31, 44, 36, 38, 41, 33, 46, 29, 52];
/** Внешний край плаща — от горба вниз до подола. */
const CAPE_EDGE = [32, 52, 27.5, 61, 22.5, 71, 18.5, 81, 14.5, 93, 11.5, 105, 9.5, 117, 10.5, 127, 12.5, 135];
/** Середина кромки лезвия в координатах топора — конец оружия для зонда (ниже всех к земле и то, чем бьют). */
const AXE_TIP: [number, number] = (() => {
  let s = 0, t = 0;
  for (let k = 0; k < AXE_EDGE.length; k += 2) {
    s += AXE_EDGE[k];
    t += AXE_EDGE[k + 1];
  }
  return [(s * 2) / AXE_EDGE.length, (t * 2) / AXE_EDGE.length];
})();
/** Точка топора (s — вдоль древка от проушины, t — поперёк, вниз от древка) в кадре от кулака (x, y) под углом `a`. */
function axePoint(x: number, y: number, a: number, s: number, t: number): [number, number] {
  const u = [Math.cos(a * DEG), Math.sin(a * DEG)], n = [-u[1], u[0]];
  const [ex, ey] = at(x, y, a, AXE_GRIP);
  return [ex + u[0] * s + n[0] * t, ey + u[1] * s + n[1] * t];
}
/** Смерть — рухнул ничком: верх ложится вперёд на колени, горб шкуры сверху. */
const FALL_ROT = 88;

function drawBerserk(p: Painter, P: BerserkPose, m: Mats): void {
  const breath = p.bob(2.5, 2);
  const turn = p.blink(0.62, 0.16);
  const fall = ease(Math.max(0, Math.min(1, P.fall)));
  const bounce = P.fall > 1 ? (P.fall - 1) * 50 : 0;
  const hipX = lerp(PELVIS[0], PELVIS[0] + 8, fall);
  const hipY = lerp(PELVIS[1] + P.crouch, G - 30, fall) - bounce;
  const rot = lerp(P.lean, FALL_ROT, fall) * DEG;
  const up = { dx: hipX - PELVIS[0], dy: hipY - PELVIS[1] - breath * (1 - fall), rot, px: PELVIS[0], py: PELVIS[1] };
  const probeInfo: Record<string, number> = {};
  const toWorld = (x: number, y: number): [number, number] => {
    const c = Math.cos(rot), s = Math.sin(rot);
    return [PELVIS[0] + c * (x - PELVIS[0]) - s * (y - PELVIS[1]) + up.dx, PELVIS[1] + s * (x - PELVIS[0]) + c * (y - PELVIS[1]) + up.dy];
  };

  p.pose({ dx: P.x, dy: P.y }, () => {
    p.shadow(70 - P.x * 0.5 + 14 * fall, 60 + 10 * fall, 4.5);

    // Упал — шкура плаща лежит на земле за спиной.
    if (fall > 0.45) p.poly([hipX - 70, G - 4, hipX - 40, G - 9, hipX - 6, G - 7, hipX + 6, G, hipX - 76, G], m.cape, { part: 'capeGround', tone: -0.12, bevel: 3 });

    // ── Плащ из шкуры — за спиной от горба до колен, виден слева и между ног; рваный подол колышется. Верх висит на
    //    плечах и дышит с ними, подол у колен стоит: в позе верха целиком подол ходил над неподвижными ногами. Падая,
    //    плащ укорачивается к горбу — лёг на спину шкурой. ──
    if (fall < 0.7) {
      const keep = 1 - fall / 0.7;
      const sway = (pts: number[]): number[] => pts.map((v, i) => (i % 2 ? v + up.dy * Math.max(0, Math.min(1, (Y(125) - v) / (Y(125) - Y(50)))) : v));
      const shrink = (pts: number[]): number[] => pts.map((v, i) => (i % 2 ? Y(40) + (v - Y(40)) * keep : v));
      p.pose({ dx: up.dx, rot, px: PELVIS[0], py: PELVIS[1] }, () => {
        const edge = furEdge(S(...CAPE_EDGE), R(4.5), R(7), -1, R(2));
        const pts = [
          ...S(104, 26, 92, 22, 80, 22, 68, 24, 58, 27, 50, 32, 42, 38, 35, 44),
          ...edge,
          ...S(12, 141, 16, 136, 20, 145, 25, 138, 30, 147, 36, 140, 44, 150, 54, 150, 62, 158, 68, 153, 74, 163, 80, 155, 86, 162, 92, 150, 98, 120, 104, 95, 110, 70, 118, 50),
        ];
        for (let k = 0; k < pts.length; k += 2) {
          const t = Math.max(0, (pts[k + 1] - 40) / 80);
          pts[k] -= P.cape * 10 * t * t;
        }
        const q = (v: number[]): number[] => shrink(sway(v));
        p.poly(q(pts), m.cape, { part: 'fur', tone: -0.06, bevel: 6 });
        locks(p, m.cape, 'fur', S(33, 58, 23, 80, 17, 104, 15, 124), { step: R(10), len: R(16), w: R(4), dir: () => 100, gap: m.capeGap, tone: 0.12, map: q });
        locks(p, m.cape, 'fur', S(48, 62, 38, 84, 30, 110, 28, 130), { step: R(10), len: R(16), w: R(4), dir: () => 96, gap: m.capeGap, tone: 0.1, shift: 0, map: q });
      });
    }

    // ── Ноги: бедро от таза, колено — ik в больших сдвигах (шаг, колено на земле, падение), стопы стоят. Штаны тёмной
    //    кожи, на колене и голени светлый мех, сапоги крупные с ремнями. Падая, оба колена на земле. ──
    const legs = [
      { g: M.legF, L2: LEG_F, side: 'far', tone: -0.08, boot: BOOT_F, bend: [1, -0.1], foot: P.footF, lift: P.liftF, kneel: fall, out: 1 },
      { g: M.legN, L2: LEG_N, side: 'near', tone: 0, boot: BOOT_N, bend: [-1, -0.3], foot: P.footN, lift: P.liftN, kneel: Math.max(P.kneel, fall), out: -1 },
    ] as const;
    for (const lg of legs) {
      const dhx = hipX - PELVIS[0], dhy = hipY - PELVIS[1];
      const hx = lg.g.hip[0] + dhx, hy = lg.g.hip[1] + dhy;
      const floor = lg.g.ank[1] - P.y;
      let ax = lg.g.ank[0] + lg.foot - P.x, ay = floor - lg.lift;
      let toe = 0;
      const kneelY = G - P.y - KNEEL_ANKLE[lg.side];
      if (lg.kneel > 0) {
        // Колено на земле под бедром, голень назад по земле к сапогу, упёртому носком.
        ax = lerp(ax, hx - lg.L2.l2 * 0.95 + R(6), lg.kneel);
        ay = lerp(ay, kneelY, lg.kneel);
        toe += KNEEL_TOE * lg.kneel;
      }
      const dax = ax - lg.g.ank[0], day = ay - lg.g.ank[1];
      const big = Math.max(Math.hypot(dhx, dhy), Math.hypot(dax, day));
      const w = lg.kneel > 0 ? 1 : Math.max(0, Math.min(1, (big - 3) / 4));
      if (w > 0) [ax, ay] = reachFoot(hx, hy, ax, ay, lg.L2.l1 + lg.L2.l2 - 0.2);
      toe += w * Math.max(0, floor - ay - lg.kneel * (floor - kneelY)) / 16;
      // Колено в стойке смотрит назад-наружу, на земле — вниз, по другую сторону линии бедро — щиколотка: сгиб ik
      // перескакивал бы на другую сторону за кадр (колено прыгало на 40 единиц). На переходе колено идёт между
      // обоими решениями — нога поворачивается в глубину и в проекции короче.
      let [ikx, iky] = ik(hx, hy, ax, ay, lg.L2.l1, lg.L2.l2, lg.bend[0], lg.bend[1]);
      if (lg.kneel > 0) {
        const [qx, qy] = ik(hx, hy, ax, ay, lg.L2.l1, lg.L2.l2, 0.3, 1);
        ikx = lerp(ikx, qx, lg.kneel);
        iky = lerp(iky, qy, lg.kneel);
      }
      const kx = lerp(lg.g.knee[0] + (dhx + dax) / 2, ikx, w), ky = lerp(lg.g.knee[1] + (dhy + day) / 2, iky, w);
      if (lg.side === 'far') probeInfo.footF = ax + P.x;
      else probeInfo.footN = ax + P.x;
      const far = lg.side === 'far';
      const leg = `${lg.side}Leg`, foot = `${lg.side}Foot`, cuff = `${lg.side}Cuff`;
      const tone = lg.tone;
      // Бедро толстое (у листа ≈ 22–28 точек), голень уже; ремень поперёк бедра.
      p.limb(hx, hy, R(far ? 15 : 14), kx, ky, R(12), m.pants, { part: leg, tone: tone + 0.1, flat: 0.3 });
      p.limb(kx, ky, R(10.5), ax, ay, R(8.5), m.pants, { part: leg, tone: tone + 0.08, flat: 0.3 });
      const [mx, my] = [lerp(hx, kx, 0.5), lerp(hy, ky, 0.5)];
      stroke(p, [mx - R(12), my - R(4), mx + R(12), my + R(1)], m.lace, leg);
      stroke(p, [mx - R(11), my - R(1), mx + R(11), my + R(4)], m.seam, leg);
      // Сапог: подошва на земле, отворот сверху, ремни; оторванная пятка и упёртый носок — поворот вокруг щиколотки.
      p.pose({ rot: toe * lg.out * 0.9, px: ax, py: ay }, () => {
        const b: number[] = [];
        for (let k = 0; k < lg.boot.length; k += 2) b.push(ax + R(lg.boot[k]), toe > 0.02 ? ay + R(lg.boot[k + 1]) : Math.min(G, ay + R(lg.boot[k + 1])));
        p.poly(b, m.boot, { part: foot, bevel: 3.4, tone: tone - 0.02 });
        stroke(p, far ? [ax - R(13), ay - R(8), ax + R(6), ay - R(8.5)] : [ax - R(3), ay - R(7), ax + R(13), ay - R(7.5)], m.lace, foot);
        stroke(p, far ? [ax - R(12), ay + R(2), ax + R(14), ay - R(1)] : [ax - R(14), ay + R(1), ax + R(12), ay + R(1)], m.seam, foot);
        stroke(p, far ? [ax + R(16), ay + R(3), ax + R(27), ay + R(7)] : [ax - R(17), ay + R(6), ax - R(10), ay + R(3)], m.lace, foot);
      });
      // Мех на колене и голени: крупные клочья вдоль голени, низ поперёк неё — пряди свисают по голени. Ровный низ и
      // отвесные пряди читались «забором».
      // Колено на земле: мех идёт за голенью (лежит назад), а не висит под коленом — иначе он уходил в землю.
      const sa = Math.atan2(ay - ky, ax - kx) / DEG;
      const ko = (sa - 90) * lg.kneel * DEG, ox = R(far ? 1 : 2), oy = R(far ? 7 : 9);
      const cx = kx + ox * Math.cos(ko) - oy * Math.sin(ko), cy = ky + ox * Math.sin(ko) + oy * Math.cos(ko);
      const rx = R(far ? 19 : 19), ry = R(far ? 10 : 11);
      const tc = Math.cos((sa - 90) * DEG), ts = Math.sin((sa - 90) * DEG);
      const turnPts = (pts: number[]): number[] => pts.map((v, i) => (i % 2 ? cy + (pts[i - 1] - cx) * ts + (v - cy) * tc : cx + (v - cx) * tc - (pts[i + 1] - cy) * ts));
      const arc: number[] = [];
      for (let k = 0; k <= 6; k++) {
        const a = Math.PI + (Math.PI * k) / 6;
        arc.push(cx + rx * Math.cos(a), cy + ry * 0.8 * Math.sin(a));
      }
      const top = furEdge(turnPts(arc), R(3.5), R(5), 1, R(1.5));
      const bottom = furEdge(turnPts([cx + rx, cy + R(3), cx + rx * 0.2, cy + R(5), cx - rx, cy + R(1)]), R(9), R(6.5), 1, 0);
      p.poly([...top, ...bottom], m.cuff, { part: cuff, bevel: 3, lift: 1, flat: 0.3, tone: tone - 0.02 });
      locks(p, m.cuff, cuff, turnPts([cx - rx * 0.75, cy - ry * 0.35, cx + rx * 0.75, cy - ry * 0.35]), { step: R(9), len: R(14), w: R(4.4), dir: (x) => sa + 9 * Math.sin(x * 1.3), gap: m.furGap, tone: 0.16 });
    }

    // ── Верх: дыхание поднимает торс, горб меха и голову; наклон и падение — в клипах. ──
    const farA = farArm(P);
    const SW = axeAngle(P, farA.a2);
    const na = nearArm(P, farA, SW);
    const held = P.drop < 0.05;
    const upA = farA.a1, upL = len([farA.sx, farA.sy], [farA.ex, farA.ey]);
    const foA = farA.a2, foL = len([farA.ex, farA.ey], [farA.hx, farA.hy]);
    // Предплечье от середины, наруч у запястья и кулак на древке; топор — под кулаком.
    const farHand = (): void => {
      if (held) axe(p, m, farA.hx, farA.hy, SW);
      p.limb(...at(farA.ex, farA.ey, foA, foL * 0.45), R(7), farA.hx, farA.hy, R(5.5), m.armF, { part: 'farArm', tone: 0.04, lift: 1, flat: 0.55 });
      stroke(p, [...at(farA.ex, farA.ey, foA - 90, R(3)), ...at(farA.ex, farA.ey, foA - 60, R(8))], m.skinDark, 'farArm');
      bracer(p, m, farA.ex, farA.ey, farA.hx, farA.hy, R(7.5), R(6.5), 0.12, 'farBracer', 0.5);
      fist(p, m, m.armF, farA.hx, farA.hy, foA, R(7.5), -0.06, 'fistF');
    };
    const layer = P.aback > 0.5 ? 'back' : P.afront > 0.5 ? 'front' : 'mid';
    p.pose(up, () => {
      // Дальняя рука висит у дальнего бока: плечо выходит из-под меха дальнего плеча и идёт вниз вдоль бока, локоть у
      // пояса смотрит назад, предплечье от него — вперёд-вниз к кулаку на древке. Край торса (дальний бок в тени)
      // закрывает внутреннюю треть плеча — рука за туловищем, но видна вся, от дельты до кулака, одной кожей. Три прежние
      // попытки держали локоть листа (132, 85) внутри силуэта торса, и рука ложилась на грудь: плечо поверх груди —
      // «спереди, анатомически неправильно», плечо за торсом — «кисть спереди, а рука сзади», полоска плеча снаружи и
      // предплечье поверх груди — «снова спереди и сломана в локте» (отзывы пользователя).
      // Плечо, локоть и начало предплечья — до торса: край торса и конец пояса закрывают их внутреннюю сторону. Тон светлее
      // и свет площе, чем у ближней руки: видна теневая сторона цилиндра, и при её тоне рука читалась тенью. Дельта под
      // мехом и бицепс — буграми вперёд, к врагам: гладкая труба читалась протезом.
      const farUp = (f: number): [number, number] => at(...at(farA.sx, farA.sy, upA, upL * f), upA - 90, R(1.5));
      p.limb(farA.sx, farA.sy, R(9.5), farA.ex, farA.ey, R(7.5), m.armF, { part: 'farArm', tone: 0.1, lift: 1, flat: 0.55 });
      p.ellipse(...farUp(0.18), R(10), R(9), m.armF, { part: 'farArm', tone: 0.12, lift: 2, flat: 0.45, rot: upA * DEG });
      p.ellipse(...farUp(0.58), R(8.5), R(7), m.armF, { part: 'farArm', tone: 0.1, lift: 2.2, flat: 0.45, rot: upA * DEG });
      p.limb(farA.ex, farA.ey, R(7.5), ...at(farA.ex, farA.ey, foA, foL * 0.4), R(7), m.armF, { part: 'farArm', tone: 0.06, lift: 1, flat: 0.55 });
      // Замах назад: топор и кисть за туловищем.
      if (layer === 'back') farHand();
      // Торс — широкий, от ближнего плеча до дальнего; грудь и пресс буграми одной части.
      p.poly(S(73, 66, 88, 62, 104, 59, 116, 57, 128, 59, 136, 64, 135, 74, 131, 84, 127, 92, 126, 97, 104, 98, 76, 97, 72, 86, 70, 72), m.torso, { part: 'torso', bevel: 6, lift: 1, tone: 0.06 });
      p.ellipse(X(96), Y(71), R(18), R(11), m.torso, { part: 'torso', lift: 2.8, flat: 0.45, tone: 0.1, rot: -0.55 });
      p.ellipse(X(121), Y(68), R(12), R(10), m.torso, { part: 'torso', lift: 2.2, flat: 0.45, tone: 0.04, rot: -0.55 });
      p.ellipse(X(113), Y(89), R(14), R(8), m.torso, { part: 'torso', lift: 1.6, flat: 0.5, tone: 0.1 });
      stroke(p, S(86, 62, 100, 60, 110, 62), m.skinLit, 'torso');
      // Подмышка — тень между плечом и грудью: без неё рука и грудь сливались в одну полосу.
      p.poly(S(72, 66, 81, 63, 85, 71, 80, 80, 72, 80), m.torso, { part: 'torso', paint: true, tone: -0.34 });
      // Тень под грудью, линия пресса.
      p.poly(S(84, 80, 98, 82, 114, 80, 112, 83, 98, 85, 88, 84), m.torso, { part: 'torso', paint: true, tone: -0.18 });
      stroke(p, S(113, 84, 112, 96), m.skinDark, 'torso');
      stroke(p, S(104, 90, 121, 89), m.skinDark, 'torso');
      // Перевязь наискось — от дальнего плеча к ближнему боку.
      p.poly(S(122, 52, 128, 55, 80, 96, 74, 93), m.strap, { part: 'torso', paint: true });
      stroke(p, S(122.5, 53, 75, 93.5), m.lace, 'torso');
      p.ellipse(X(104), Y(75), R(3.2), R(3.2), m.buckle, { part: 'strapRing', lift: 1 });

      // Кожаная юбка под поясом: ближний бок со светлой меховой полосой, дальний — тёмные ремни.
      p.poly(S(106, 97, 142, 94, 145, 106, 142, 119, 136, 113, 130, 121, 124, 114, 116, 121, 108, 115), m.pants, { part: 'skirtF', bevel: 2.5, tone: -0.1 });
      p.poly(S(72, 96, 90, 98, 90, 112, 86, 123, 80, 117, 73, 126, 68, 119, 62, 122, 64, 110), m.pants, { part: 'skirtN', bevel: 2.5 });
      p.poly([...S(56, 121, 68, 116, 80, 120, 89, 128), ...furEdge(S(89, 131, 56, 127), R(4), R(4), 1, 0)], m.cuff, { part: 'hipFur', bevel: 2 });
      p.poly(S(68, 99, 76, 99, 78, 112, 73, 117, 69, 109), m.cuff, { part: 'hipFur', bevel: 1.6, tone: 0.05 });

      // Набедренная повязка — красная, рваный низ; на выпаде относит назад.
      const tf = P.cape * 5;
      p.poly(S(88, 99, 106, 99, 107, 120, 106 - tf, 145, 106 - tf, 160, 103 - tf, 167, 100 - tf, 158, 97 - tf, 165, 94 - tf, 157, 91 - tf, 163, 88 - tf, 156, 87 - tf * 0.5, 140, 87, 120), m.cloth, { part: 'cloth', bevel: 2.4 });
      stroke(p, S(93, 104, 92 - tf, 150), m.fold, 'cloth');
      stroke(p, S(101, 104, 101 - tf, 152), m.fold, 'cloth');

      // Пояс из круглых бляшек, ромб-пряжка. Дальний конец — у края торса: дальше висит локоть дальней руки, и пояс,
      // уходивший до x 142, закрывал его — рука снова рвалась на плечо и предплечье.
      p.poly(S(72, 90, 105, 92, 132, 89, 133, 98, 105, 101, 72, 99), m.belt, { part: 'belt', bevel: 2 });
      for (let k = 0; k < 6; k++) {
        const bx = 76 + k * 10.5;
        if (bx > 90 && bx < 102) continue;
        p.ellipse(X(bx), Y(95.5 - (bx - 76) * 0.04), R(4.2), R(4), m.belt, { part: 'belt', lift: 1.2, tone: 0.1 });
      }
      p.poly(S(96, 89, 101.5, 95, 96, 102, 90.5, 95), m.buckle, { part: 'buckle', bevel: 1.6, lift: 1.2 });

      // Дальний бок в тени — между грудью и рукой, как у ближней подмышки.
      p.poly(S(127, 76, 134, 72, 131, 84, 127, 92, 124, 86), m.torso, { part: 'torso', paint: true, tone: -0.3 });
      // Предплечье идёт от локтя к зрителю и врагам — перед юбкой и древком, поэтому его вторая половина рисуется после
      // них, но той же частью `farArm`: без линии на стыке кожа идёт одной поверхностью от плеча до обмотки (отдельная
      // часть давала шов на локте — рука читалась сломанной). Складка — с внутренней стороны сгиба. Предплечье голое,
      // наруч — только у запястья: тёмный наруч во всё предплечье сливался с кожей юбки, и кулак висел сам по себе.
      if (layer === 'mid') farHand();

      // Горб меха на плечах — выше головы, пряди от шеи вниз; нижний край рваный над грудью и плечом.
      const top = furEdge(S(...MANTLE_TOP), R(5), R(6), -1, -R(2));
      const fringe = furEdge(S(29, 51, 40, 55, 52, 57, 64, 59, 76, 60, 86, 60), R(4), R(5), -1, 0);
      p.poly([...top, ...fringe, ...S(92, 54, 96, 46, 99, 38, 103, 31)], m.mantle, { part: 'fur', bevel: 8, flat: 0.25, lift: 3 });
      p.ellipse(X(78), Y(38), R(30), R(14), m.mantle, { part: 'fur', lift: 4, flat: 0.3 });
      const rows: Array<[number[], number]> = [
        [[104, 23, 92, 21, 80, 20, 68, 23, 58, 26, 50, 31, 43, 37, 37, 43], 0.5],
        [[106, 35, 94, 32, 82, 31, 70, 33, 60, 36, 52, 41, 45, 47], 0],
        [[106, 48, 94, 46, 82, 46, 70, 48, 60, 50], 0.5],
      ];
      for (const [row, shift] of rows) locks(p, m.mantle, 'fur', S(...row), { step: R(10), len: R(15), w: R(4.2), dir: fromNeck, gap: m.furGap, tone: 0.22, shift });

      p.poly(S(97, 46, 101, 40, 108, 38, 111, 50, 110, 62, 102, 66, 95, 60), m.torso, { part: 'neck', bevel: 2.5, tone: -0.32 });
      stroke(p, S(99, 46, 97, 60), m.skinDark, 'neck');
      // Мех на дальнем плече — узкой полосой вокруг шеи справа от головы, в тени; голова садится в него. Низ лежит на
      // дельте дальней руки, рука выходит из-под него у края: мех до y 78 закрывал плечо почти до локтя, и от руки
      // оставалась полоска.
      const collar = [...S(114, 52, 122, 48, 129, 44, 134, 44, 137, 50, 139, 56, 141, 62), ...furEdge(S(142, 64, 136, 68, 131, 74, 125, 71, 120, 64), R(5), R(4), 1, 0), ...S(113, 58)];
      p.poly(collar, m.collar, { part: 'collar', bevel: 3.5, lift: 1.5, tone: -0.1 });
      locks(p, m.collar, 'collar', S(118, 54, 128, 52, 138, 60), { step: R(6), len: R(10), w: R(2.6), dir: () => 80, gap: m.furGap, tone: 0.12 });

      // Голова — после меха: верх ворота (y 44–52) проходил по лицу, и мех закрывал низ лица и всю бороду. Борода
      // теперь свисает на мех. Раз за цикл голова подаётся к врагам на пиксель.
      p.pose({ dx: 1.5 * turn, rot: P.head * DEG, px: M.neck[0], py: M.neck[1] }, () => wolfHead(p, m));

      // Топор перед головой и горбом (блок древком, топор вскинут перед собой).
      if (layer === 'front') farHand();

      // Край горба над ближним плечом — поверх верха руки, рваной бахромой; рука, поднятая над плечом (`nfur`), вышла
      // из-под шкуры — край рисуется до неё.
      const furOver = (): void => {
        const over = [...S(30, 50, 42, 45, 56, 48, 70, 50, 84, 52), ...furEdge(S(86, 56, 70, 58, 56, 58, 42, 56, 32, 54), R(4.5), R(4.5), 1, 0)];
        p.poly(over, m.mantle, { part: 'fur', bevel: 3, flat: 0.3, lift: 3 });
        locks(p, m.mantle, 'fur', S(80, 51, 66, 50, 52, 49, 40, 48), { step: R(8), len: R(9), w: R(3), dir: fromNeck, gap: m.furGap, tone: 0.14, shift: 0.25 });
      };
      if (P.nfur > 0.5) furOver();

      // Ближняя рука — поверх торса: голое плечо с бицепсом, кожаный наруч с обмоткой, кулак.
      const ua = Math.atan2(na.ey - na.sy, na.ex - na.sx) / DEG, ul = len([na.sx, na.sy], [na.ex, na.ey]);
      // Плечо — дельта у сустава и бицепс книзу, свет сверху: гладкая «колбаса» читалась протезом.
      const along = (f: number, off = 0): [number, number] => at(...at(na.sx, na.sy, ua, ul * f), ua + 90, off);
      p.limb(na.sx, na.sy, R(9), na.ex, na.ey, R(7.5), m.armN, { part: 'nearArm', lift: 1, flat: 0.3, tone: -0.02 });
      p.ellipse(...along(0.22, -R(1)), R(12), R(9.5), m.armN, { part: 'nearArm', lift: 2.8, rot: ua * DEG, flat: 0.3, tone: 0 });
      p.ellipse(...along(0.6, R(1.5)), R(10.5), R(8.5), m.armN, { part: 'nearArm', lift: 2.6, rot: ua * DEG, flat: 0.3, tone: -0.02 });
      // Граница дельты и бицепса, блик по верху плеча, тень под бицепсом.
      stroke(p, [...along(0.44, -R(3)), ...along(0.4, R(8))], m.skinDark, 'nearArm');
      stroke(p, [...along(0.1, -R(8)), ...along(0.32, -R(8.5)), ...along(0.7, -R(7))], m.skinLit, 'nearArm');
      stroke(p, [...along(0.45, R(9.5)), ...along(0.78, R(8.5))], m.skinDark, 'nearArm');
      const fa = Math.atan2(na.hy - na.ey, na.hx - na.ex) / DEG;
      bracer(p, m, na.ex, na.ey, na.hx, na.hy, R(14), R(12), 0, 'nearBracer');
      fist(p, m, m.armN, na.hx, na.hy, fa, R(11), 0, 'fistN');

      if (P.nfur <= 0.5) furOver();

      // Искры о древко в кадр удара по блоку.
      if (P.spark > 0.05) {
        const [cx, cy] = at(farA.hx, farA.hy, SW, P.nd * 0.5);
        const n = Math.round(7 * P.spark);
        for (let k = 0; k < n; k++) {
          const [x, y] = at(cx, cy, -150 + k * 30, 3 + 5 * P.spark + (k % 2) * 2.5);
          p.px(x, y, k % 2 ? '#ffd890' : '#fff6d8');
        }
        p.glow(cx, cy, 5 * P.spark, '#ffc870', 0.5);
      }
    });

    // Топор выпал: из кулака летит на землю перед ногами и ложится лезвием вверх.
    if (!held) {
      const k = ease(Math.min(1, P.drop));
      const [hx0, hy0] = toWorld(farA.hx, farA.hy);
      const x = lerp(hx0, 150, k), y = lerp(hy0, G - 3, k * k);
      const a = lerp(SW + rot / DEG, 178, k);
      axe(p, m, x, y, a);
    }
    const [tipX, tipY] = toWorld(...axePoint(farA.hx, farA.hy, SW, AXE_TIP[0], AXE_TIP[1]));
    if (P.dust > 0.05) {
      // Пыль от лезвия, ударившего в землю.
      const dx0 = Math.min(tipX, 160);
      for (let k = 0; k < 9; k++) {
        const r = (2 + 4 * P.dust) * (0.6 + ((k * 37) % 5) / 8);
        p.disc(dx0 + (k - 4) * 5 * P.dust, G - 2 - (k % 3) * 3 * P.dust - (k % 2) * 2, r * 0.5, k % 2 ? '#7a6c58c0' : '#9a8a70c0', true);
      }
    }

    if (berserkProbe.on) {
      const [hwx, hwy] = toWorld(farA.hx, farA.hy);
      // Запястье — угол топора к предплечью, локоть — угол между плечом и предплечьем (180 — прямая рука).
      const wrist = nrm(SW - farA.a2), elbow = 180 - Math.abs(nrm(farA.a2 - farA.a1));
      const [swx, swy] = toWorld(farA.sx, farA.sy), [ewx, ewy] = toWorld(farA.ex, farA.ey), [bwx, bwy] = toWorld(...at(farA.hx, farA.hy, SW, -AXE_BUTT));
      const [nwx, nwy] = toWorld(na.hx, na.hy), [nex, ney] = toWorld(na.ex, na.ey), [nsx, nsy] = toWorld(na.sx, na.sy);
      berserkProbe.on({
        ...probeInfo, hipX: hipX + P.x, hipY: hipY + P.y, handX: hwx + P.x, handY: hwy + P.y, tipX: tipX + P.x, tipY: tipY + P.y, ground: G, wrist, elbow,
        shX: swx + P.x, shY: swy + P.y, elX: ewx + P.x, elY: ewy + P.y, butX: bwx + P.x, butY: bwy + P.y,
        nHandX: nwx + P.x, nHandY: nwy + P.y, nElX: nex + P.x, nElY: ney + P.y, nShX: nsx + P.x, nShY: nsy + P.y,
        nElbow: 180 - Math.abs(nrm(na.a2 - na.a1)),
      });
    }
  });
}

/**
 * Наруч — кожаная обмотка от чуть ниже локтя до кулака, с плоским верхним краем (капсула закрывала локоть и низ плеча),
 * `w0`/`w1` — полуширина сверху и у запястья; поперёк — тёмные стыки и светлый ремень. `from` — где начинается обмотка,
 * доля предплечья от локтя: у дальней руки — с середины.
 */
function bracer(p: Painter, m: Mats, ex: number, ey: number, hx: number, hy: number, w0: number, w1: number, tone: number, part: string, from = 0.16): void {
  const fa = Math.atan2(hy - ey, hx - ex) / DEG, l = len([ex, ey], [hx, hy]);
  const nx = Math.cos((fa + 90) * DEG), ny = Math.sin((fa + 90) * DEG);
  const [ax, ay] = at(ex, ey, fa, l * from), [bx, by] = at(ex, ey, fa, l * 0.94);
  p.poly([ax - nx * w0, ay - ny * w0, ax + nx * w0, ay + ny * w0, bx + nx * w1, by + ny * w1, bx - nx * w1, by - ny * w1], m.bracer, { part, bevel: Math.min(w0, w1) * 0.8, tone });
  for (const [f0, c] of [[0.3, m.seam], [0.52, m.lace], [0.58, m.lace], [0.8, m.seam]] as const) {
    const f = from + ((f0 - 0.16) * (0.94 - from)) / 0.78;
    const [cx, cy] = at(ex, ey, fa, l * f);
    const w = lerp(w0, w1, (f - from) / (0.94 - from));
    stroke(p, [cx - nx * w, cy - ny * w - 0.8, cx + nx * w, cy + ny * w + 0.8], c, part);
  }
  // Светлый край обмотки сверху.
  stroke(p, [ax - nx * w0 * 0.9, ay - ny * w0 * 0.9 + 0.7, ax + nx * w0 * 0.9, ay + ny * w0 * 0.9 + 0.7], m.lace, part);
}

/**
 * Кулак: шире предплечья, костяшки к врагам (по ходу предплечья `fa`), пальцы — тёмные черты поперёк, большой палец
 * сверху, блик.
 */
function fist(p: Painter, m: Mats, mat: Mat, x: number, y: number, fa: number, r: number, tone: number, part: string): void {
  p.ellipse(x, y, r * 1.15, r * 0.85, mat, { part, lift: 1.2, tone, rot: (fa + 90) * DEG });
  const ux = Math.cos(fa * DEG), uy = Math.sin(fa * DEG), nx = -uy, ny = ux;
  for (const t of [-0.35, 0.1, 0.55]) stroke(p, [x + nx * r * t + ux * r * 0.2, y + ny * r * t + uy * r * 0.2, x + nx * r * t + ux * r * 0.8, y + ny * r * t + uy * r * 0.8], m.skinDark, part);
  p.ellipse(x - nx * r * 0.75 - ux * r * 0.1, y - ny * r * 0.75 - uy * r * 0.1, r * 0.4, r * 0.34, mat, { part, lift: 2, tone: tone + 0.06 });
  p.poly([x - r * 0.7, y - r * 0.4, x - r * 0.25, y - r * 0.75, x + r * 0.1, y - r * 0.65, x - r * 0.35, y - r * 0.2], mat, { part, paint: true, tone: tone + 0.28 });
}
