export const TRAITS: Record<string, TraitDef> = Object.fromEntries(list.map((t) => [t.id, t]));
export const TRAIT_LIST: TraitDef[] = list;

export function traitDef(id: string): TraitDef {
  const def = TRAITS[id];
  if (!def) throw new Error(`Unknown trait: ${id}`);
  return def;
}
